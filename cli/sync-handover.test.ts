import fs from "node:fs";
import path from "node:path";

import { afterAll, expect, it } from "vitest";

import {
  HANDOVER,
  copied,
  dropFixture,
  exists,
  git,
  plain,
  read,
  readJson,
  sync,
} from "./sync/__fixtures__/copied-install.ts";
import { expectMode } from "./sync/__fixtures__/file-mode.ts";
import { useTempDirs } from "./sync/__fixtures__/temp-dirs.ts";
import { MANIFEST_REL, renderManifest } from "./sync/manifest.ts";

useTempDirs();

afterAll(dropFixture);

const SLOW = 180_000;
const HEADER = "<!-- @generated by @workerstack/repo -->";

function rule(text: string) {
  return `---\ndescription: Team\n---\n${text}\n`;
}

function mcp(servers: Record<string, unknown>) {
  return `${JSON.stringify({ mcpServers: servers }, null, 2)}\n`;
}

const REGION = /^<!-- repo:rules [\da-f]{8} -->\n[\s\S]*?\n<!-- \/repo:rules -->\n/;

/** The `--check` and apply lines of the old layout below, in order. */
const MOVES = [
  ".repo/rules/agents.md into AGENTS.md below repo:rules",
  "packages/web/.repo/rules/style.md into packages/web/AGENTS.md below repo:rules",
  ".repo/mcp.json servers into .mcp.json",
  ".repo/mcp-policy.jsonc servers into .mcp.json",
];

type Servers = { mcpServers: Record<string, unknown> };

function lines(text: string) {
  return text.split("\n");
}

/** A consumer on the old layout: pathless rules, both MCP overlays, read-only owned files and an old manifest. */
function oldLayout(): string {
  const root = plain({
    ".gitignore": "# >>> @workerstack/repo (generated by repo sync)\nAGENTS.md\n.mcp.json\n# <<< @workerstack/repo\n",
    ".mcp.json": mcp({ docs: { command: "own" } }),
    ".repo/mcp-policy.jsonc": '// ours\n{ "allow": ["pol"], "servers": { "pol": { "command": "p" } } }\n',
    ".repo/mcp.json": mcp({ docs: { command: "theirs" }, extra: { command: "e" } }),
    ".repo/rules/agents.md": rule("Always run the linter."),
    "AGENTS.md": `${HEADER}\nold stock text\n`,
    [MANIFEST_REL]: renderManifest([".mcp.json", "AGENTS.md", "packages/web/CLAUDE.md"]),
    "package.json": JSON.stringify({ name: "app", workspaces: ["packages/*"] }),
    "packages/web/.repo/rules/style.md": rule("Use the ui kit."),
    "packages/web/CLAUDE.md": `${HEADER}\nStart at references/INDEX.md in this package.\n`,
    "packages/web/package.json": JSON.stringify({ name: "@app/web" }),
    "packages/web/references/INDEX.md": "# Web\n",
  });

  for (const rel of ["AGENTS.md", ".mcp.json"]) fs.chmodSync(path.join(root, rel), 0o444);

  return root;
}

it(
  "--check names each move and the count, exits 1 and writes nothing",
  async () => {
    const root = oldLayout();
    const result = await sync(root, ["--check"], true);
    expect(result.code).toBe(1);
    expect(result.err).toStrictEqual([
      ...MOVES.map((move) => `repo sync: would move ${move}\n`),
      "repo sync: 4 handover steps pending; run `bun repo sync`\n",
    ]);
    expect(exists(root, ".repo/mcp.json")).toBe(true);
    expect(read(root, "AGENTS.md")).toBe(`${HEADER}\nold stock text\n`);
  },
  SLOW,
);

it(
  "hands every source over in one sync, keeps the user's files writable and tracked, and the next sync is up to date",
  async () => {
    const root = oldLayout();
    const result = await sync(root, [], true);
    expect(result.code, result.err.join("")).toBe(0);
    const out = result.out.join("");

    for (const move of MOVES) expect(out).toContain(`repo sync: moved ${move}\n`);
    expect(out).toContain(`repo sync: kept .mcp.json's own "docs" server; dropped the one in .repo/mcp.json\n`);
    expect(out).toContain("removed packages/web/CLAUDE.md");
    const agents = read(root, "AGENTS.md");
    expect(agents).toMatch(REGION);
    expect(agents.replace(REGION, "")).toBe("\nAlways run the linter.\n");
    expect(read(root, "packages/web/AGENTS.md").replace(REGION, "")).toBe("\nUse the ui kit.\n");
    expect(readJson<Servers>(root, ".mcp.json").mcpServers).toStrictEqual({
      docs: { command: "own" },
      extra: { command: "e" },
      pol: { command: "p" },
    });
    expect(read(root, ".repo/mcp-policy.jsonc")).toBe('// ours\n{ "allow": ["pol"] }\n');

    for (const gone of [".repo/mcp.json", ".repo/rules/agents.md", "packages/web/.repo/rules/style.md"])
      expect(exists(root, gone), gone).toBe(false);

    expect(exists(root, "packages/web/CLAUDE.md")).toBe(false);

    for (const rel of ["AGENTS.md", ".mcp.json"]) expectMode(root, rel, 0o644);
    expect(lines(read(root, ".gitignore"))).not.toContain("AGENTS.md");
    expect(lines(read(root, ".gitignore"))).not.toContain(".mcp.json");
    expect(await sync(root, ["--check"], true)).toStrictEqual({ code: 0, err: [], out: ["repo sync: up to date\n"] });
  },
  SLOW,
);

it(
  "stops on a bad .mcp.json with its named error and writes nothing",
  async () => {
    const root = oldLayout();
    fs.chmodSync(path.join(root, ".mcp.json"), 0o644);
    fs.writeFileSync(path.join(root, ".mcp.json"), '{\n  "mcpServers": {\n  ,\n}');
    const result = await sync(root, [], true);
    expect(result.code).toBe(1);
    expect(result.err).toStrictEqual([
      "repo sync: mcp policy: .mcp.json: not valid JSON at line 3; fix it, nothing written\n",
    ]);
    expect(exists(root, ".repo/rules/agents.md")).toBe(true);
    expect(read(root, "AGENTS.md")).toBe(`${HEADER}\nold stock text\n`);
  },
  SLOW,
);

it(
  "keeps a tracked .mcp.json that carries the header, made headerless and writable",
  async () => {
    const own = mcp({ a: { command: "x" } });
    const root = plain({ ".mcp.json": `// @generated by @workerstack/repo\n${own}` });
    fs.chmodSync(path.join(root, ".mcp.json"), 0o444);
    git(root, "add", "-A");
    const result = await sync(root, [], true);
    expect(result.code, result.err.join("")).toBe(0);
    expect(result.out[0]).toBe("repo sync: made .mcp.json yours: writable, without the generated header\n");
    expect(read(root, ".mcp.json")).toBe(own);
    expectMode(root, ".mcp.json", 0o644);
    expect(git(root, "ls-files", ".mcp.json")).toBe(".mcp.json\n");
  },
  SLOW,
);

it(
  "leaves a pathless rule that overrides a stock one in .repo/rules and renders its body in AGENTS.md",
  async () => {
    const own = "Reply in short plain sentences.";
    const root = plain({ ".repo/rules/overview.md": `---\ndescription: Ours\noverrides: overview\n---\n${own}\n` });
    const result = await sync(root, [], true);
    expect(result.code, result.err.join("")).toBe(0);
    const agents = read(root, "AGENTS.md");
    expect(agents).toContain(own);
    expect(agents).not.toContain("en-US default.");
    expect(exists(root, ".repo/rules/overview.md")).toBe(true);
    expect(await sync(root, ["--check"], true)).toStrictEqual({ code: 0, err: [], out: ["repo sync: up to date\n"] });
  },
  SLOW,
);

it(
  "hands it over in the same sync that migrates it, and the next sync is up to date",
  async () => {
    const root = copied();
    const result = await sync(root, [], true);
    expect(result.code, result.err.join("")).toBe(0);

    for (const line of HANDOVER) expect(result.out).toContain(`${line}\n`);
    expect(read(root, "AGENTS.md").replace(REGION, "")).toBe(
      "\nOur team notes: ship on Fridays only with a rollback plan.\n\nTeam rule: run `make lint` before every push.\n",
    );
    expect(readJson<Servers>(root, ".mcp.json").mcpServers).toStrictEqual({
      docs: { args: ["-y", "docs-mcp"], command: "npx" },
    });
    expect(read(root, ".repo/mcp-policy.jsonc")).not.toContain("servers");
    expect(await sync(root, ["--check"], true)).toStrictEqual({ code: 0, err: [], out: ["repo sync: up to date\n"] });
  },
  SLOW,
);
