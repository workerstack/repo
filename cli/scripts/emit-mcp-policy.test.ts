import fs from "node:fs";
import path from "node:path";

import { expect, it } from "vitest";

import { BASE_POLICY } from "./__fixtures__/mcp-base-policy.ts";
import { plant, plantDirs, plantPolicy, readJsonAs, readTomlAs } from "./__fixtures__/mcp-policy-kit.ts";
import { isHomeGrokConfig } from "./emit-mcp-hosts.ts";
import { emitMcpPolicy } from "./emit-mcp-policy.ts";

const tmpDir = plantDirs();

type ClaudeSettings = {
  enableAllProjectMcpServers: boolean;
  enabledMcpjsonServers: string[];
  permissions: { deny: string[] };
  hooks?: unknown;
};

type McpFile = {
  mcpServers: Record<string, unknown>;
};

type GrokFile = {
  plugins?: { enabled?: unknown[]; deny_default?: boolean };
  permission?: { deny?: string[]; allow?: string[] };
  permissions?: unknown;
  mcp?: unknown;
  mcp_servers?: Record<string, { enabled?: boolean; command?: string }>;
};

type CodexFile = {
  agents?: { max_depth?: number };
  mcp_servers?: Record<string, unknown>;
};

/** Writes `<root>/.mcp.json` holding `servers`, as the user keeps it. */
function writeMcpJson(root: string, servers: Record<string, unknown>): string {
  const text = `${JSON.stringify({ mcpServers: servers }, null, 2)}\n`;
  plant(root, ".mcp.json", text);

  return text;
}

function seedHostStubs(ws: string): void {
  const settings = {
    hooks: { PreToolUse: [{ matcher: "Agent" }] },
    permissions: { deny: ["Agent(Explore)", "Agent(Plan)", "Agent(general-purpose)"] },
  };

  plant(ws, ".claude/settings.json", `${JSON.stringify(settings, null, 2)}\n`);
  plant(ws, ".codex/config.toml", "[agents]\nmax_depth = 1\n");
}

function expectGrokDenyAll(ws: string): void {
  const grokRaw = fs.readFileSync(path.join(ws, ".grok/config.toml"), "utf8");
  expect(grokRaw).not.toContain("Generated by");
  expect(grokRaw).not.toMatch(/\[features\]/);
  expect(grokRaw).not.toMatch(/\[\[permissions\]\]/);
  expect(grokRaw).not.toMatch(/deny_default/);
  expect(grokRaw).not.toMatch(/\[mcp\.servers/);
  const grok = readTomlAs<GrokFile>(ws, ".grok/config.toml");
  expect(grok.plugins?.enabled).toStrictEqual([]);
  expect(grok.plugins?.deny_default).toBeUndefined();
  expect(grok.mcp).toBeUndefined();
  expect(grok.mcp_servers).toBeUndefined();
  expect(grok.permissions).toBeUndefined();
  expect(grok.permission?.deny).toContain("MCPTool");
  expect(grok.permission?.allow ?? []).toStrictEqual([]);
}

function expectClaudeAndCodexDenyAll(ws: string): void {
  const claude = readJsonAs<ClaudeSettings>(ws, ".claude/settings.json");
  expect(claude.enableAllProjectMcpServers).toBe(false);
  expect(claude.enabledMcpjsonServers).toStrictEqual([]);
  expect(claude.permissions.deny).toContain("mcp__*");
  expect(claude.permissions.deny).toContain("Agent(Explore)");
  expect(claude.permissions.deny).toContain("Agent(Plan)");
  expect(claude.hooks).toBeTruthy();
  const codex = readTomlAs<CodexFile>(ws, ".codex/config.toml");
  expect(codex.agents?.max_depth).toBe(1);
  expect(codex.mcp_servers).toBeUndefined();
}

it("deny-all emit on tmp workspaceRoot", () => {
  const ws = tmpDir("emit-mcp-deny-");
  const home = tmpDir("emit-mcp-home-");
  const homeCfg = plant(home, ".grok/config.toml", "keep = true\n");
  plantPolicy(ws, BASE_POLICY);
  seedHostStubs(ws);
  const r = emitMcpPolicy({ check: false, workspaceRoot: ws });
  expect(r.ok).toBe(true);
  expect(fs.readFileSync(homeCfg, "utf8")).toBe("keep = true\n");
  expect(fs.existsSync(path.join(ws, ".mcp.json"))).toBe(false);
  expect(readJsonAs<McpFile>(ws, ".agents/mcp_config.json")).toStrictEqual({ mcpServers: {} });
  expectGrokDenyAll(ws);
  expectClaudeAndCodexDenyAll(ws);
});

function expectGrokAllowsNotes(ws: string): void {
  const grok = readTomlAs<GrokFile>(ws, ".grok/config.toml");
  expect(grok.plugins?.enabled).toStrictEqual([]);
  expect(grok.permission?.deny).toContain("MCPTool");
  expect(grok.permission?.allow).toContain("MCPTool(notes__*)");
  expect(grok.mcp).toBeUndefined();
  expect(grok.mcp_servers?.stale?.enabled).toBe(false);
  expect(grok.mcp_servers?.stale?.command).toBe("old");
  expect(grok.mcp_servers?.notes?.command).toBe("npx");
}

it("named-allow fixture emits only that server; leftover grok disabled", () => {
  const ws = tmpDir("emit-mcp-allow-");
  plantPolicy(ws, { ...BASE_POLICY, allow: ["notes"] });
  const own = writeMcpJson(ws, { extra: { command: "nope" }, notes: { args: ["-y", "notes-mcp"], command: "npx" } });
  seedHostStubs(ws);
  plant(ws, ".grok/config.toml", '[mcp_servers.stale]\ncommand = "old"\nenabled = true\n');
  plant(ws, ".codex/config.toml", '[agents]\nmax_depth = 1\n\n[mcp_servers.stale]\ncommand = "old"\n');
  expect(emitMcpPolicy({ check: false, workspaceRoot: ws }).ok).toBe(true);
  expect(fs.readFileSync(path.join(ws, ".mcp.json"), "utf8")).toBe(own);
  expect(Object.keys(readJsonAs<McpFile>(ws, ".agents/mcp_config.json").mcpServers)).toStrictEqual(["notes"]);
  expectGrokAllowsNotes(ws);
  expect(readJsonAs<ClaudeSettings>(ws, ".claude/settings.json").enabledMcpjsonServers).toStrictEqual(["notes"]);
  const codex = readTomlAs<CodexFile>(ws, ".codex/config.toml");
  expect(Object.keys(codex.mcp_servers ?? {})).toStrictEqual(["notes"]);
  expect(codex.mcp_servers?.stale).toBeUndefined();
});

it("project [features] is drift", () => {
  const ws = tmpDir("emit-mcp-feat-");
  const home = tmpDir("emit-mcp-feat-home-");
  plantPolicy(ws, BASE_POLICY);
  seedHostStubs(ws);
  expect(emitMcpPolicy({ check: false, home, workspaceRoot: ws }).ok).toBe(true);
  fs.appendFileSync(path.join(ws, ".grok/config.toml"), "\n[features]\ntwo_pass_compaction = true\n");
  expect(isHomeGrokConfig(ws, home)).toBe(false);
  const drifted = emitMcpPolicy({ check: true, home, workspaceRoot: ws });
  expect(drifted.ok).toBe(false);
  expect(String(drifted.error)).toMatch(/\.grok\/config\.toml/);
});

it("home workspace keeps [features] and check passes", () => {
  const home = tmpDir("emit-mcp-feat-home-");
  plantPolicy(home, BASE_POLICY);
  seedHostStubs(home);
  expect(emitMcpPolicy({ check: false, home, workspaceRoot: home }).ok).toBe(true);
  const homeGrok = path.join(home, ".grok/config.toml");
  fs.appendFileSync(homeGrok, '\n[agent]\nname = "orchestrator"\n\n[features]\ntwo_pass_compaction = true\n');
  expect(isHomeGrokConfig(home, home)).toBe(true);
  expect(emitMcpPolicy({ check: true, home, workspaceRoot: home }).ok).toBe(true);
  expect(emitMcpPolicy({ check: false, home, workspaceRoot: home }).ok).toBe(true);
  const after = fs.readFileSync(homeGrok, "utf8");
  expect(after).toMatch(/two_pass_compaction/);
  expect(after).toMatch(/orchestrator/);
});

it("--check fails on drift then passes; writes nothing on check", () => {
  const ws = tmpDir("emit-mcp-check-");
  plantPolicy(ws, BASE_POLICY);
  seedHostStubs(ws);
  expect(emitMcpPolicy({ check: false, workspaceRoot: ws }).ok).toBe(true);
  expect(emitMcpPolicy({ check: true, workspaceRoot: ws }).ok).toBe(true);
  const mcpPath = path.join(ws, ".agents/mcp_config.json");
  const before = fs.readFileSync(mcpPath, "utf8");
  fs.writeFileSync(mcpPath, `${JSON.stringify({ mcpServers: { leaked: {} } }, null, 2)}\n`);
  const drifted = emitMcpPolicy({ check: true, workspaceRoot: ws });
  expect(drifted.ok).toBe(false);
  expect(String(drifted.error)).toMatch(/drift/);
  expect(fs.readFileSync(mcpPath, "utf8")).not.toBe(before);
  fs.writeFileSync(mcpPath, before);
  expect(emitMcpPolicy({ check: true, workspaceRoot: ws }).ok).toBe(true);
});

const stockPolicy = { ...BASE_POLICY, allow: ["a"] };
const servers = { a: { command: "a" }, b: { command: "b" }, c: { command: "c" } };

it("reads the stock policy from sourceRoot and writes only under workspaceRoot", () => {
  const stock = tmpDir("mcp-stock-");
  const out = tmpDir("mcp-out-");
  plantPolicy(stock, stockPolicy);
  writeMcpJson(out, servers);
  expect(emitMcpPolicy({ sourceRoot: stock, workspaceRoot: out }).ok).toBe(true);
  expect(emitMcpPolicy({ check: true, sourceRoot: stock, workspaceRoot: out }).ok).toBe(true);
  expect(Object.keys(readJsonAs<McpFile>(out, ".agents/mcp_config.json").mcpServers)).toStrictEqual(["a"]);
  expect(fs.readdirSync(stock)).toStrictEqual(["agents"]);
  expect(fs.readdirSync(path.join(stock, "agents"))).toStrictEqual(["mcp-policy.jsonc"]);
});

it("deep-merges <consumerRoot>/.repo/mcp-policy.jsonc over the stock policy", () => {
  const [stock, consumer, out] = [tmpDir("mcp-stock-"), tmpDir("mcp-consumer-"), tmpDir("mcp-out-")];
  plantPolicy(stock, stockPolicy);
  plant(consumer, ".repo/mcp-policy.jsonc", '// own\n{ "allow": ["a", "c"] }\n');
  writeMcpJson(consumer, servers);
  expect(emitMcpPolicy({ consumerRoot: consumer, sourceRoot: stock, workspaceRoot: out }).ok).toBe(true);
  expect(readJsonAs<McpFile>(out, ".agents/mcp_config.json").mcpServers).toStrictEqual({
    a: { command: "a" },
    c: { command: "c" },
  });
});
