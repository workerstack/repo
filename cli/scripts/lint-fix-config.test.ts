import { expect, it } from "vitest";
import { z } from "zod";

import { readJson } from "../json.ts";
import { fixConfig } from "./lint-fix-config.ts";

const CATEGORIES = ["correctness", "suspicious", "pedantic", "perf", "style", "restriction", "nursery"];

const SORT_KEYS = ["error", "asc", { caseSensitive: true }];

const CONFIG = `// @generated by @workerstack/repo\n${JSON.stringify({
  categories: { correctness: "error", pedantic: "error", style: "warn" },
  env: { node: true },
  globals: { Bun: "readonly" },
  ignorePatterns: ["**/__fixtures__/**"],
  jsPlugins: [{ name: "repo", specifier: "@workerstack/repo/lint" }],
  options: { typeAware: true },
  overrides: [
    {
      env: { vitest: true },
      files: ["**/*.test.ts"],
      globals: { it: "readonly" },
      jsPlugins: [{ name: "extra", specifier: "extra-plugin" }],
      plugins: ["vitest"],
      rules: { "eslint/sort-keys": "off", "repo/max-line-width": "warn", "vitest/expect-expect": "error" },
    },
    { files: ["**/*.config.ts"], rules: { "import/no-default-export": "off" } },
  ],
  plugins: ["eslint", "vitest"],
  rules: {
    "eslint/no-console": "error",
    "eslint/sort-keys": SORT_KEYS,
    "repo/max-line-width": ["error", { max: 120 }],
  },
  settings: { vitest: { typecheck: true } },
})}`;

function fixed(text: string | null, over: string[]) {
  return readJson(z.record(z.string(), z.json()), fixConfig(text, over));
}

it("sets every category off", () => {
  expect(fixed(CONFIG, ["eslint(sort-keys)"]).categories).toStrictEqual(
    Object.fromEntries(CATEGORIES.map((name) => [name, "off"])),
  );
});

it("keeps only the over keys, with their real value and options", () => {
  const config = fixed(CONFIG, ["eslint(sort-keys)", "repo(max-line-width)"]);
  expect(config.rules).toStrictEqual({
    "eslint/sort-keys": SORT_KEYS,
    "repo/max-line-width": ["error", { max: 120 }],
  });
});

it("sets an over category rule the config does not list to error", () => {
  expect(fixed(CONFIG, ["eslint(curly)"]).rules).toStrictEqual({ "eslint/curly": "error" });
});

it("cuts each override's rules to the over keys and keeps its other fields", () => {
  const config = fixed(CONFIG, ["repo(max-line-width)"]);
  expect(config.overrides).toStrictEqual([
    {
      env: { vitest: true },
      files: ["**/*.test.ts"],
      globals: { it: "readonly" },
      jsPlugins: [{ name: "extra", specifier: "extra-plugin" }],
      plugins: ["vitest"],
      rules: { "repo/max-line-width": "warn" },
    },
  ]);
});

it("drops an override left with no over key", () => {
  const config = fixed(CONFIG, ["eslint(no-console)"]);
  expect(config.overrides).toStrictEqual([]);
});

it("drops a script rule and a key neither the config nor the catalog knows", () => {
  const config = fixed(CONFIG, ["repo(duplicate-code)", "repo(not-a-rule)", "eslint(sort-keys)"]);
  expect(config.rules).toStrictEqual({ "eslint/sort-keys": SORT_KEYS });
});

it("reads a missing config as an empty one", () => {
  const config = fixed(null, ["eslint(curly)", "repo(max-line-width)"]);
  expect(config.rules).toStrictEqual({ "eslint/curly": "error" });
  expect(config.categories).toStrictEqual(Object.fromEntries(CATEGORIES.map((name) => [name, "off"])));
  expect(config.overrides).toStrictEqual([]);
});

it("keeps plugins, jsPlugins, options, settings, env, globals and ignorePatterns", () => {
  const config = fixed(CONFIG, ["eslint(sort-keys)"]);
  expect(config).toMatchObject({
    env: { node: true },
    globals: { Bun: "readonly" },
    ignorePatterns: ["**/__fixtures__/**"],
    jsPlugins: [{ name: "repo", specifier: "@workerstack/repo/lint" }],
    options: { typeAware: true },
    plugins: ["eslint", "vitest"],
    settings: { vitest: { typecheck: true } },
  });
});
