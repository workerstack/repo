/** Temp dirs, git repos among them, for the tests of the json key sorter. */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

/** A json file with its keys out of order, first at "hooks", and the same file sorted. */
export const UNSORTED = '{\n  "name": "x",\n  "hooks": {\n    "Stop": 1,\n    "Pre": 2\n  }\n}\n';
export const SORTED = '{\n  "hooks": {\n    "Pre": 2,\n    "Stop": 1\n  },\n  "name": "x"\n}\n';

const temps: string[] = [];

/** Removes every dir made since the last call; each test file runs it after each test. */
export function cleanJsonDirs(): void {
  for (const folder of temps.splice(0)) fs.rmSync(folder, { recursive: true, force: true });
}

/** A temp dir with `files` written under it; `repo` makes it a git repo. */
export function jsonDir(files: Record<string, string> = {}, repo = true): string {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "workerstack-json-keys-")));
  temps.push(root);
  if (repo) execFileSync("git", ["init", "-q", "-b", "main"], { cwd: root });
  for (const [rel, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), text);
  }
  return root;
}

/** The oxfmt config sync writes: a comment line, then JSON. */
export const ignoreConfig = (ignorePatterns: string[]): string =>
  `// Generated by repo sync. Do not edit.\n${JSON.stringify({ printWidth: 120, ignorePatterns }, null, 2)}\n`;

/** The top-level keys of a json object's text, in the order written. */
export const keysOf = (text: string): string[] => Object.keys(JSON.parse(text) /* an object */ as object);

export const readText = (root: string, rel: string): string => fs.readFileSync(path.join(root, rel), "utf8");
