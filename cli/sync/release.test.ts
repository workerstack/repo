import { BASE_CONFIG } from "../fixtures/base-config.ts";
import { describe, expect, it } from "vitest";
import type { Pack } from "../config.ts";
import { GENERATORS, type SyncContext } from "./outputs.ts";
import { release } from "./release.ts";
import type { PackageJson } from "./workspace.ts";

const HEADER = "# Generated by repo sync. Do not edit.";
const CI_PATH = ".github/workflows/ci.yml";

function context(packs: Pack[], manifest: PackageJson = {}, files: Record<string, string> = {}): SyncContext {
  return {
    root: "/repo",
    config: { packs, agents: { hosts: [], skills: [] }, ...BASE_CONFIG },
    workspace: { root: "/repo", manifest, packages: [] },
    read: (rel) => files[rel] ?? null,
  };
}

const CHECKOUT = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1";
const SETUP_BUN = "oven-sh/setup-bun@0c5077e51419868618aeaa5fe8019c62421857d6 # v2.2.0";

const HEAD = `${HEADER}
name: ci

on:
  push:
    branches: [main]
  pull_request:
  workflow_dispatch:

concurrency:
  group: ci-\${{ github.workflow }}-\${{ github.ref }}
  cancel-in-progress: true

permissions:
  contents: read

jobs:
  test:
    name: test (\${{ matrix.os }})
    runs-on: \${{ matrix.os }}
    timeout-minutes: 30
    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-latest, windows-latest, macos-latest]
    steps:
      - uses: ${CHECKOUT}
      - uses: ${SETUP_BUN}
        with:
          bun-version-file: package.json
      - name: Refuse to run as root
        if: runner.os != 'Windows'
        run: |
          if [ "$(id -u)" = "0" ]; then echo "CI must run as a non-root user; the suite assumes unprivileged file permissions"; exit 1; fi
      - run: bun install --frozen-lockfile
      - run: bun repo ci

  no-node:
    name: no-node
    runs-on: ubuntu-latest
    timeout-minutes: 40
    steps:
      - uses: ${CHECKOUT}
      - uses: ${SETUP_BUN}
        with:
          bun-version-file: package.json
      - name: Remove node
        run: |
          sudo rm -f $(which -a node nodejs)
          sudo rm -rf /opt/hostedtoolcache/node
          hash -r
      - name: Assert node is gone
        run: |
          if command -v node; then echo "node is still on PATH"; exit 1; fi
      - run: bun install --frozen-lockfile
      - run: bun repo ci
`;

const NO_NODE_SHALLOW = `    steps:
      - uses: ${CHECKOUT}
      - uses: ${SETUP_BUN}
        with:
          bun-version-file: package.json
      - name: Remove node`;
const NO_NODE_FULL = NO_NODE_SHALLOW.replace(
  `- uses: ${CHECKOUT}`,
  `- uses: ${CHECKOUT}\n        with:\n          fetch-depth: 0`,
);

const E2E_IN_NO_NODE = `      - run: bun run test:e2e
`;

const E2E_JOB = `
  e2e:
    name: e2e (\${{ matrix.os }})
    runs-on: \${{ matrix.os }}
    timeout-minutes: 40
    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-latest, windows-latest, macos-latest]
    defaults:
      run:
        shell: bash
    steps:
      - uses: ${CHECKOUT}
        with:
          fetch-depth: 0
      - uses: ${SETUP_BUN}
        with:
          bun-version-file: package.json
      - run: bun install --frozen-lockfile
      - run: bun run test:e2e
`;

const lookup = (ctx: SyncContext) => release(ctx).outputs[0];

describe("release", () => {
  it("writes the whole tracked ci.yml without an e2e job when the root has no test:e2e script", () => {
    expect(release(context(["release"]))).toEqual({
      outputs: [{ kind: "file", path: CI_PATH, content: HEAD, tracked: true, managed: "whole" }],
      errors: [],
    });
  });

  it("adds the e2e step and job when the root has a test:e2e script", () => {
    const manifest: PackageJson = { scripts: { "test:e2e": "vitest" } };
    expect(lookup(context(["release"], manifest))).toEqual({
      kind: "file",
      path: CI_PATH,
      content: HEAD.replace(NO_NODE_SHALLOW, NO_NODE_FULL) + E2E_IN_NO_NODE + E2E_JOB,
      tracked: true,
      managed: "whole",
    });
  });

  it("ignores a scripts field that is not an object with a test:e2e string", () => {
    expect(lookup(context(["release"], { scripts: "nope" }))).toMatchObject({ content: HEAD });
    expect(lookup(context(["release"], { scripts: { "test:e2e": 1 } }))).toMatchObject({ content: HEAD });
    expect(lookup(context(["release"], { scripts: null }))).toMatchObject({ content: HEAD });
  });

  it("never uses setup-node", () => {
    const manifest: PackageJson = { scripts: { "test:e2e": "vitest" } };
    const output = lookup(context(["release"], manifest));
    expect(output?.kind === "file" && output.content.includes("setup-node")).toBe(false);
  });
});

describe("release gates", () => {
  it("is a generator", () => {
    expect(GENERATORS).toContain(release);
  });

  it("writes nothing with the pack off", () => {
    expect(release(context(["agents", "standards", "docs"]))).toEqual({ outputs: [], errors: [] });
  });

  it("rewrites a ci.yml that has the generated header on its first line", () => {
    const result = release(context(["release"], {}, { [CI_PATH]: `${HEADER}\nname: old\n` }));
    expect(result.errors).toEqual([]);
    expect(result.outputs).toHaveLength(1);
  });

  it("refuses a hand-written ci.yml", () => {
    expect(release(context(["release"], {}, { [CI_PATH]: "name: ci\n" }))).toEqual({
      outputs: [],
      errors: [".github/workflows/ci.yml is hand-written; delete it so repo sync can own it"],
    });
  });
});
