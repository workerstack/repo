import { execFileSync } from "node:child_process";
import path from "node:path";

import { parse } from "jsonc-parser";
import { expect, it } from "vitest";

import { readGoldens } from "../../dev/capture-tree-goldens.ts";
import { HOSTS } from "../config.ts";
import {
  IGNORE_BASE,
  attributes,
  block,
  file,
  gitattributesOf,
  gitignoreOf,
  link,
  readonlyOf,
  region,
  settingsOf,
} from "./__fixtures__/git-files-kit.ts";
import { put, tempDir, useTempDirs } from "./__fixtures__/temp-dirs.ts";
import { byCodeUnit } from "./by-code-unit.ts";
import { listedFiles } from "./git-files.ts";
import type { Output } from "./outputs.ts";

useTempDirs();

const goldens = [...readGoldens().keys()];

/** Each golden as the trees generator plans it: AGENTS.md a tracked shared file, every other one owned whole. */
function planned({ tracked }: { tracked: boolean }) {
  return goldens.map((rel) => (rel === "AGENTS.md" ? file(rel, true, "block") : file(rel, tracked)));
}

const owned = goldens.filter((rel) => rel !== "AGENTS.md");
const goldenOutputs = planned({ tracked: false });

it(
  "are ignored by host dir, read-only by exact path, and marked generated by none " +
    "(a consumer commits none but AGENTS.md)",
  () => {
    const fixture = { hosts: [...HOSTS] };
    expect(gitignoreOf(fixture, goldenOutputs)).toBe(block(".agents/", ".claude/", ".codex/", ".cursor/", ".grok/"));
    expect(readonlyOf(settingsOf(fixture, goldenOutputs))).toStrictEqual(owned.toSorted(byCodeUnit));
    expect(gitattributesOf(fixture, goldenOutputs)).toBe(attributes());
  },
);

it("are marked generated one line each when the repo commits them", () => {
  const lines = gitattributesOf({ hosts: [...HOSTS] }, planned({ tracked: true })).split("\n");
  expect(lines.filter((line) => line.endsWith(" linguist-generated"))).toStrictEqual(
    owned.toSorted(byCodeUnit).map((rel) => `${rel} linguist-generated`),
  );
});

it("lists tracked and untracked files git does not ignore, with extra ignore lines applied, sorted", () => {
  const root = tempDir("workerstack-listed-");
  execFileSync("git", ["init", "-q"], { cwd: root });

  for (const rel of ["b.ts", "a/x.ts", "skip/y.ts", "ignored.log"]) put(root, rel, "x");
  put(root, ".gitignore", "*.log\n");
  expect(listedFiles(root, ["skip/"])).toStrictEqual([".gitignore", "a/x.ts", "b.ts"]);
  expect(listedFiles(path.join(root, "missing"), [])).toBeNull();
});

function packageOutputs({ tracked }: { tracked: boolean }): Output[] {
  return [
    file("packages/web/AGENTS.md", true, "block"),
    file("packages/web/CLAUDE.md", tracked),
    link("packages/web/.claude/skills/deploy", tracked),
    file(".claude/rules/packages/web/x.md", tracked),
  ];
}

it(
  "lists each untracked package output by its exact path, beside the collapsed host dir, " +
    "and never its shared AGENTS.md",
  () => {
    expect(gitignoreOf({ hosts: ["claude"] }, packageOutputs({ tracked: false }))).toBe(
      block("packages/web/.claude/skills/deploy", "packages/web/CLAUDE.md", ".claude/"),
    );
  },
);

it("marks tracked package files generated and read-only by exact path, and ignores nothing", () => {
  const outputs = packageOutputs({ tracked: true });
  expect(gitignoreOf({ hosts: ["claude"], name: "@workerstack/repo" }, outputs)).toBe(region("ignore", IGNORE_BASE));
  expect(gitattributesOf({}, outputs)).toContain("packages/web/CLAUDE.md linguist-generated\n");
  expect(gitattributesOf({}, outputs)).not.toContain("packages/web/AGENTS.md");
  const settings: unknown = parse(settingsOf({}, outputs));
  expect(settings).not.toHaveProperty(["files.readonlyInclude", "packages/web/AGENTS.md"]);
  expect(settings).toMatchObject({ "files.readonlyInclude": { "packages/web/CLAUDE.md": true } });
});
