import { describe, expect, it } from "vitest";

import { closeMarker, markerLine, openMarker, regionBlock } from "../fixtures/region-markers.ts";
import { cutRegions, regionBody, regionHash, syntaxOf, writeRegions } from "./region.ts";
import type { Region, RegionSyntax } from "./region.ts";

const SYNTAXES: readonly RegionSyntax[] = ["#", "<!--"];
const ALPHA: Region = { body: "one\ntwo", name: "alpha", place: "bottom" };
const BETA: Region = { body: "three", name: "beta", place: "bottom" };
const EMPTY: Region = { body: "", name: "empty", place: "bottom" };
const RULES: Region = { body: "rule", name: "rules", place: "top" };
const IGNORE: Region = { body: "node_modules/\n.repo/tmp/", name: "ignore", place: "bottom" };
const OLD = "zero";

/**
 * The lines a row's text is written in, `|` between lines: `A` `B` `E` `R` are the ALPHA, BETA, EMPTY and RULES
 * regions as sync writes them; `<a` opens alpha with its body's hash, `<a0` with the old body's, `<a-` with none;
 * `a>` closes it; `<e-` opens empty with no hash; `<g` `<g-` `g>` are the markers of a region no version writes;
 * `H` is an owned header line. Any other line stands for itself.
 */
function tokens(syntax: RegionSyntax): Record<string, string> {
  return {
    "<a": openMarker(syntax, "alpha", regionHash(ALPHA.body)),
    "<a-": openMarker(syntax, "alpha"),
    "<a0": openMarker(syntax, "alpha", regionHash(OLD)),
    "<e-": openMarker(syntax, "empty"),
    "<g": openMarker(syntax, "gone", regionHash("x")),
    "<g-": openMarker(syntax, "gone"),
    A: regionBlock(syntax, ALPHA),
    B: regionBlock(syntax, BETA),
    E: regionBlock(syntax, EMPTY),
    H: markerLine(syntax, "@generated by @workerstack/repo"),
    R: regionBlock(syntax, RULES),
    "a>": closeMarker(syntax, "alpha"),
    "g>": closeMarker(syntax, "gone"),
  };
}

function text(syntax: RegionSyntax, rows: string): string {
  const table = tokens(syntax);
  return rows === ""
    ? ""
    : `${rows
        .split("|")
        .map((row) => table[row] ?? row)
        .join("\n")}\n`;
}

/** The regions a row writes, named after the tokens of their blocks. */
const [a, ab, e, r, none] = [[ALPHA], [ALPHA, BETA], [EMPTY], [RULES], []] as const;
/** Name, text before, text after, the one repair line or none, the regions written. */
type Row = readonly [string, string, string, string, readonly Region[]];

const ROWS: readonly Row[] = [
  ["one region in order", "top||A||end", "top||A||end", "", a],
  ["no markers, bottom", "user", "user||A", "", a],
  ["no markers, bottom of an empty file", "", "A||B", "", ab],
  ["no markers, top", "Title", "R||Title", "", r],
  ["no markers, top of an empty file", "", "R", "", r],
  ["no markers, top after an owned header", "H||body", "H|R||body", "", r],
  ["no markers, top after frontmatter", "---|name: x|---|body", "---|name: x|---|R||body", "", r],
  ["no markers, top with an unclosed fence", "---|body", "R||---|body", "", r],
  ["open only, body to the end", "user|<a|one|two", "user|A", "closed repo:alpha", a],
  ["open only, the user's line after", "<a|one|mine", "A|mine", "closed repo:alpha", a],
  ["open only, empty body", "<e-|user", "E|user", "closed repo:empty", e],
  ["close only", "one|two|a>|user", "A|user", "opened repo:alpha", a],
  ["close before open", "mine|one|a>|mid|<a|one|last", "mine|mid|A|last", "reordered the markers of repo:alpha", a],
  ["two regions", "<a0|zero|a>||user||<a|mine|a>", "A||user", "dropped 1 extra repo:alpha", a],
  ["a stray open before a region", "<a|one|A", "A", "dropped 1 stray marker of repo:alpha", a],
  ["a region and a stray open", "A|<a|one", "A", "dropped 1 stray marker of repo:alpha", a],
  ["a region and two stray closes", "a>|A|a>|user", "A|user", "dropped 2 stray markers of repo:alpha", a],
  [
    "hash mismatch",
    "<a|one|mine|two|also mine|a>|after",
    "A|mine|also mine|after",
    "moved 2 edited lines out of repo:alpha",
    a,
  ],
  ["hash mismatch, one line and a blank", "<a|one||two|mine|a>", "A|mine", "moved 1 edited line out of repo:alpha", a],
  ["hash mismatch, a line deleted", "<a|one|a>", "A", "", a],
  ["hash match", "<a0|zero|a>", "A", "", a],
  ["missing hash", "user||<a-|zero|a>", "user||A", "added the hash to repo:alpha", a],
  ["unknown region cut", "user||<g|x|g>||A", "user||A", "cut repo:gone", a],
  ["unknown stray hashed open cut", "<g|user", "user||A", "cut repo:gone", a],
  ["no regions, every region cut", "user||A", "user", "cut repo:alpha", none],
];

const MANGLED: Record<RegionSyntax, readonly (readonly [string, string])[]> = {
  "#": [
    ["open", `#REPO : Alpha ${regionHash(ALPHA.body)}\none\ntwo\n# /repo:alpha\n`],
    ["close", `# repo:alpha ${regionHash(ALPHA.body)}\none\ntwo\n#  / Repo:ALPHA\n`],
  ],
  "<!--": [
    ["open", `<!--repo:ALPHA ${regionHash(ALPHA.body).toUpperCase()}-->\none\ntwo\n<!-- /repo:alpha -->\n`],
    ["close", `<!-- repo:alpha ${regionHash(ALPHA.body)} -->\none\ntwo\n<!--   / repo : alpha   -->\n`],
  ],
};

const LEGACY =
  "node_modules/\n\n# >>> @workerstack/repo (generated by repo sync)\n.repo/tmp/\n# <<< @workerstack/repo\n";

/** How many lines of `body` are a marker of `name`, read loosely in either syntax. */
function markersOf(body: string, name: string): number {
  const marker = new RegExp(`^(#|<!--)\\s*/?\\s*repo\\s*:\\s*${name}\\b`, "i");
  return body.split("\n").filter((line) => marker.test(line)).length;
}

/** The two properties every repaired file holds: one exact region per name, and a second pass finds nothing to do. */
function expectSettled(syntax: RegionSyntax, regions: readonly Region[], after: string): void {
  for (const region of regions) {
    expect(markersOf(after, region.name)).toBe(2);
    expect(after).toContain(regionBlock(syntax, region));
  }
  expect(markersOf(after, "(?!(?:alpha|beta|empty|rules|ignore)\\b)\\w+")).toBe(0);
  expect(writeRegions(after, syntax, regions)).toStrictEqual({ repairs: [], text: after });
}

describe.each(SYNTAXES)("writeRegions in %s syntax", (syntax) => {
  it.each(ROWS)("%s", (...row) => {
    const [, before, after, repair, regions] = row;
    const result = { repairs: repair === "" ? [] : [repair], text: text(syntax, after) };
    expect(writeRegions(text(syntax, before), syntax, regions)).toStrictEqual(result);
    expectSettled(syntax, regions, result.text);
  });

  it.each(MANGLED[syntax])("rewrites a mangled %s marker in the exact form", (_which, before) => {
    const result = { repairs: ["rewrote the markers of repo:alpha"], text: text(syntax, "A") };
    expect(writeRegions(before, syntax, [ALPHA])).toStrictEqual(result);
    expectSettled(syntax, [ALPHA], result.text);
  });

  it("reads CRLF, a BOM and trailing space, and writes LF", () => {
    const before = `﻿user\r\n${tokens(syntax)["<a"]}  \r\none\r\ntwo\r\n${closeMarker(syntax, "alpha")}\r\n`;
    expect(writeRegions(before, syntax, [ALPHA])).toStrictEqual({ repairs: [], text: text(syntax, "user|A") });
    expectSettled(syntax, [ALPHA], text(syntax, "user|A"));
  });
});

describe("the legacy git pair", () => {
  it("converts to the one region of a hash file", () => {
    const after = `node_modules/\n\n${regionBlock("#", IGNORE)}\n`;
    expect(writeRegions(LEGACY, "#", [IGNORE])).toStrictEqual({
      repairs: ["converted the old markers to repo:ignore"],
      text: after,
    });
    expectSettled("#", [IGNORE], after);
  });

  it("is cut when no region is written", () => {
    expect(writeRegions(LEGACY, "#", [])).toStrictEqual({ repairs: ["cut the old markers"], text: "node_modules/\n" });
  });

  it("is plain text in markdown, where a hash line is a heading", () => {
    expect(writeRegions(LEGACY, "<!--", [IGNORE]).text).toBe(`${LEGACY}\n${regionBlock("<!--", IGNORE)}\n`);
  });

  it("needs the exact package name", () => {
    const before = "# >>> @workerstack/repository\nx\n# <<< @workerstack/repository\n";
    expect(writeRegions(before, "#", [IGNORE]).text).toBe(`${before}\n${regionBlock("#", IGNORE)}\n`);
  });
});

describe("cutRegions", () => {
  it.each(SYNTAXES)("cuts every region and stray marker in %s syntax, keeping the user's lines", (syntax) => {
    const before = text(syntax, "a||A||b|<g|c");
    expect(cutRegions(before, syntax)).toStrictEqual({
      repairs: ["cut repo:alpha", "cut repo:gone"],
      text: "a\n\nb\nc\n",
    });
    expect(cutRegions("a\n\nb\nc\n", syntax)).toStrictEqual({ repairs: [], text: "a\n\nb\nc\n" });
  });

  it("cuts the legacy pair", () => {
    expect(cutRegions(LEGACY, "#")).toStrictEqual({ repairs: ["cut the old markers"], text: "node_modules/\n" });
  });

  it("leaves nothing when the file held only regions", () => {
    expect(cutRegions(text("#", "A||B"), "#")).toStrictEqual({
      repairs: ["cut repo:alpha", "cut repo:beta"],
      text: "",
    });
  });

  it("returns a file with no marker byte for byte", () => {
    expect(cutRegions("﻿a\r\nb  \r\n", "#")).toStrictEqual({ repairs: [], text: "﻿a\r\nb  \r\n" });
  });
});

describe("regionBody", () => {
  it.each([
    ["a hashed pair", "x\n<!-- repo:stack 1a2b3c4d -->\none\ntwo\n<!-- /repo:stack -->\ny\n"],
    ["an unhashed pair", "<!-- repo:stack -->\none\ntwo\n<!-- /repo:stack -->\n"],
    ["a mangled pair, CRLF and a BOM", "﻿<!--repo : STACK-->  \r\none\r\ntwo\r\n<!--  / repo:stack   -->\r\n"],
  ])("reads the body of %s", (_, source) => {
    expect(regionBody(source, "<!--", "stack")).toBe("one\ntwo");
  });

  it("reads the first region of a name, an empty one as empty, and the legacy pair in a hash file", () => {
    const twice = "<!-- repo:x -->\n<!-- /repo:x -->\n<!-- repo:x -->\nlater\n<!-- /repo:x -->\n";
    expect(regionBody(twice, "<!--", "x")).toBe("");
    expect(regionBody(LEGACY, "#", "ignore")).toBe(".repo/tmp/");
  });

  it("is undefined when the region is missing, unclosed or closed before it opens", () => {
    for (const source of [
      "a\n",
      "<!-- repo:x -->\nrest\n",
      "<!-- /repo:x -->\n<!-- repo:x -->\n",
      "<!-- repo:y -->\n<!-- /repo:y -->\n",
    ])
      expect(regionBody(source, "<!--", "x")).toBeUndefined();
  });
});

describe("regionHash", () => {
  it("is the first 8 hex of the body's sha256", () => {
    expect(regionHash("")).toBe("e3b0c442");
  });

  it("ignores the body's trailing newline, as the body ends with its last line", () => {
    expect(regionHash("one\ntwo\n")).toBe(regionHash("one\ntwo"));
    expect(regionHash("one\ntwo")).toMatch(/^[\da-f]{8}$/);
  });
});

describe("syntaxOf", () => {
  it.each([
    ["references/INDEX.md", "<!--"],
    ["packages/web/references/INDEX.MD", "<!--"],
    [".gitignore", "#"],
    [".gitattributes", "#"],
  ])("%s takes %s", (rel, syntax) => {
    expect(syntaxOf(rel)).toBe(syntax);
  });
});
