import { describe, expect, it } from "vitest";

import { agentsFile, isAgentsFile } from "./agents-file.ts";
import type { Output } from "./outputs.ts";
import { regionHash } from "./region.ts";
import { hashText } from "./stock-history.ts";

const BODY = "Stock rule.\n\n## Rules by path\n- `src/**`: read `.repo/rules/src.md`\n";
/** The `repo:rules` region holding `body`, as sync writes it. */
function region(body: string) {
  return `<!-- repo:rules ${regionHash(body)} -->\n${body}<!-- /repo:rules -->\n`;
}
const STOCK_COPY = "# Agents\n\nThe stock text a copied install shipped.\n";
const HISTORY = { "AGENTS.md": [hashText(STOCK_COPY)] };
const REPLACED = "replaced the old stock rules with repo:rules";
const POINTER = "Start at references/INDEX.md in this package.\n";

function run(text: string | null, rel = "AGENTS.md", body = BODY) {
  return agentsFile(rel, body, { history: HISTORY, text });
}
function contentOf(output: Output) {
  return output.kind === "file" ? output.content : "";
}

describe("agentsFile", () => {
  it("turns a missing file into a tracked block holding the hashed region alone", () => {
    expect(run(null)).toStrictEqual({
      content: region(BODY),
      kind: "file",
      managed: "block",
      path: "AGENTS.md",
      tracked: true,
    });
  });

  it("puts the region on top of a file with no marker and keeps the user's text below it", () => {
    expect(contentOf(run("My notes.\r\n\r\nMore.\n"))).toBe(`${region(BODY)}\nMy notes.\n\nMore.\n`);
  });

  it("rewrites the region in place and keeps the user's text above and below it byte for byte", () => {
    const disk = `Above.\n\n${region("old stock\n")}\nBelow  \n- list\n`;
    expect(run(disk)).not.toHaveProperty("repairs");
    expect(contentOf(run(disk))).toBe(`Above.\n\n${region(BODY)}\nBelow  \n- list\n`);
  });
});

describe("agentsFile over text no user wrote", () => {
  it("drops a whole generated file, a stock-unedited copy and the old repo:begin blocks as none of the user's", () => {
    expect(contentOf(run("<!-- @generated by @workerstack/repo -->\nOld stock.\n"))).toBe(region(BODY));
    expect(contentOf(run(STOCK_COPY.replaceAll("\n", "\r\n")))).toBe(region(BODY));
    expect(contentOf(run("Mine.\n<!-- repo:begin -->\nOld stock.\n<!-- repo:end -->\n"))).toBe(
      `${region(BODY)}\nMine.\n`,
    );
  });

  it("keeps a package file that matches the root's stock history, since that history names the root alone", () => {
    expect(contentOf(run(STOCK_COPY, "packages/web/AGENTS.md"))).toBe(`${region(BODY)}\n${STOCK_COPY}`);
  });
});

describe("agentsFile over an old file's stock rules", () => {
  it("puts the region where the stock rules stood, the user's lines above and below kept, and says so", () => {
    expect(run(`Team note\n${STOCK_COPY}Ship note\n`)).toMatchObject({
      content: `Team note\n${region(BODY)}Ship note\n`,
      repairs: [REPLACED],
    });
  });

  it("cuts the old repo:begin blocks beside the stock rules and still replaces those", () => {
    const old = "<!-- repo:begin -->\nOld stock.\n<!-- repo:end -->\n";
    expect(run(`${old}Team note\n${STOCK_COPY}Ship note\n${old}`)).toMatchObject({
      content: `Team note\n${region(BODY)}Ship note\n`,
      repairs: [REPLACED],
    });
  });

  it("replaces a package file's old text, which is the body itself", () => {
    expect(run(`x\n${POINTER}y\n`, "packages/web/AGENTS.md", POINTER)).toMatchObject({
      content: `x\n${region(POINTER)}y\n`,
      repairs: [REPLACED],
    });
  });

  it("leaves the region alone in an unedited old file, and says so", () => {
    expect(run(STOCK_COPY)).toMatchObject({ content: region(BODY), repairs: [REPLACED] });
  });

  it("keeps stock rules the user edited on any line as theirs, below the region on top", () => {
    const edited = `Team note\n${STOCK_COPY.replace("stock text", "our text")}Ship note\n`;
    expect(run(edited)).not.toHaveProperty("repairs");
    expect(contentOf(run(edited))).toBe(`${region(BODY)}\n${edited}`);
  });
});

describe("agentsFile repairs", () => {
  it("reports the repairs it made and none on a second pass over its own output", () => {
    const first = run(`Mine.\n\n<!-- repo:rules -->\n${BODY}<!-- /repo:rules -->\n`);
    expect(first).toMatchObject({ repairs: ["added the hash to repo:rules"] });
    const second = run(contentOf(first));
    expect(second).not.toHaveProperty("repairs");
    expect(contentOf(second)).toBe(contentOf(first));
  });
});

describe("the always-on budget", () => {
  const big = `${"x".repeat(13_350)}\n`;

  it("warns on a root file over 12 KiB, in KiB to one decimal", () => {
    expect(run(null, "AGENTS.md", big)).toMatchObject({
      repairs: ["always-on text is 13.1 KiB, over the 12 KiB budget; move some to a path rule or a skill"],
    });
  });

  it("counts the user's text too, and never warns on a package file or a root file within the budget", () => {
    expect(run(big)).toMatchObject({ repairs: [expect.stringMatching(/^always-on text is 13\.\d KiB/)] });
    expect(run(null, "packages/web/AGENTS.md", big)).not.toHaveProperty("repairs");
    expect(run(`${"x".repeat(12_000)}\n`, "AGENTS.md", "Short.\n")).not.toHaveProperty("repairs");
  });
});

describe("isAgentsFile", () => {
  it("names the root and every package AGENTS.md, and nothing else", () => {
    expect(isAgentsFile("AGENTS.md")).toBe(true);
    expect(isAgentsFile("packages/web/AGENTS.md")).toBe(true);
    expect(isAgentsFile("docs/NOT-AGENTS.md")).toBe(false);
    expect(isAgentsFile(".claude/rules/AGENTS.md.bak")).toBe(false);
  });
});
