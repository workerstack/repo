import { describe, expect, it } from "vitest";
import type { Pack } from "../config.ts";
import type { Host } from "../config.ts";
import { bunfig, GENERATORS, gitignore, index, lessons, trees, type Output, type SyncContext } from "./outputs.ts";
import type { PackageJson, WorkspacePackage } from "./workspace.ts";

const BUNFIG = '# Generated by repo sync. Do not edit.\n[install]\nlinker = "hoisted"\nauto = "disable"\n';
const SELF_BLOCK = "# >>> @workerstack/repo (generated by repo sync)\n.tmp/\n.worktrees/\n.repo/tmp/\n# <<< @workerstack/repo\n";
const BLOCK = "# >>> @workerstack/repo (generated by repo sync)\n.tmp/\n.worktrees/\n.repo/tmp/\nnode_modules/\n# <<< @workerstack/repo\n";
const blockOf = (...lines: string[]) =>
  `# >>> @workerstack/repo (generated by repo sync)\n${[".tmp/", ".worktrees/", ".repo/tmp/", "node_modules/", ...lines].join("\n")}\n# <<< @workerstack/repo\n`;

type Fixture = {
  hosts?: Host[];
  packs?: Pack[];
  manifest?: PackageJson;
  packages?: WorkspacePackage[];
  files?: Record<string, string>;
};

/** A sync context over in-memory files; `read` sees only `files`. */
function context({ hosts = [], packs = ["docs"], manifest = {}, packages = [], files = {} }: Fixture = {}): SyncContext {
  return {
    root: "/repo",
    config: { packs, agents: { hosts, skills: [] } },
    workspace: { root: "/repo", manifest, packages },
    read: (rel) => files[rel] ?? null,
  };
}

/** The text of a file output. */
function contentOf(output: Output | undefined): string | undefined {
  return output?.kind === "file" ? output.content : undefined;
}

const API: WorkspacePackage = { dir: "packages/api", manifest: { name: "@acme/api" } };
const WEB: WorkspacePackage = { dir: "apps/web", manifest: { name: "web" } };
const PACKAGE_INDEXES = {
  "packages/api/references/INDEX.md": "\n\n# API worker\n\nMore.\n",
  "apps/web/references/INDEX.md": "Web app\r\n",
};
const PACKAGES_SECTION =
  "<!-- repo:packages -->\n" +
  "- [web](../apps/web/references/INDEX.md): Web app\n" +
  "- [@acme/api](../packages/api/references/INDEX.md): API worker\n" +
  "<!-- /repo:packages -->";
const REPO_STACK =
  "<!-- repo:stack -->\n" +
  "- [@workerstack/repo](../node_modules/@workerstack/repo/references/INDEX.md)\n" +
  "<!-- /repo:stack -->";
const EMPTY_STACK = "<!-- repo:stack -->\n<!-- /repo:stack -->";

describe("GENERATORS", () => {
  it("runs bunfig, gitignore, index, lessons and trees in that order", () => {
    expect(GENERATORS).toEqual([bunfig, gitignore, index, lessons, trees]);
  });
});

describe("bunfig", () => {
  it("writes the generated bunfig.toml when none exists", () => {
    expect(bunfig(context())).toEqual({ outputs: [{ kind: "file", path: "bunfig.toml", content: BUNFIG, tracked: true }], errors: [] });
  });

  it("returns the same content when the file is current", () => {
    expect(bunfig(context({ files: { "bunfig.toml": BUNFIG } }))).toEqual({
      outputs: [{ kind: "file", path: "bunfig.toml", content: BUNFIG, tracked: true }],
      errors: [],
    });
  });

  it("owns a stale file that still starts with the generated header", () => {
    const stale = '# Generated by repo sync. Do not edit.\r\n[install]\r\nlinker = "isolated"\r\n';
    expect(bunfig(context({ files: { "bunfig.toml": stale } })).outputs).toEqual([
      { kind: "file", path: "bunfig.toml", content: BUNFIG, tracked: true },
    ]);
  });

  it("refuses a hand-written bunfig.toml", () => {
    expect(bunfig(context({ files: { "bunfig.toml": '[test]\nroot = "x"\n' } }))).toEqual({
      outputs: [],
      errors: ["bunfig.toml is hand-written; delete it so repo sync can own it"],
    });
  });
});

describe("gitignore", () => {
  const gitignoreWith = (text: string | undefined) =>
    gitignore(context({ files: text === undefined ? {} : { ".gitignore": text } }));

  it("writes the block alone when .gitignore is missing or empty", () => {
    const only = { outputs: [{ kind: "file", path: ".gitignore", content: BLOCK, tracked: true }], errors: [] };
    expect(gitignoreWith(undefined)).toEqual(only);
    expect(gitignoreWith("")).toEqual(only);
    expect(gitignoreWith("\n\n")).toEqual(only);
  });

  it("appends the block after one blank line, adding a missing trailing newline first", () => {
    expect(gitignoreWith("node_modules").outputs).toEqual([
      { kind: "file", path: ".gitignore", content: `node_modules\n\n${BLOCK}`, tracked: true },
    ]);
  });

  it("appends after existing entries and keeps hand-written duplicates of the block lines", () => {
    expect(gitignoreWith("node_modules/\n.tmp/\n\n\n").outputs).toEqual([
      { kind: "file", path: ".gitignore", content: `node_modules/\n.tmp/\n\n${BLOCK}`, tracked: true },
    ]);
  });

  it("replaces the block in place, matching the begin marker by prefix and keeping the text around it", () => {
    const text = "dist/\n# >>> @workerstack/repo (old label)\n.cache/\n# <<< @workerstack/repo\n\n.env\n";
    expect(gitignoreWith(text).outputs).toEqual([{ kind: "file", path: ".gitignore", content: `dist/\n${BLOCK}\n.env\n`, tracked: true }]);
  });

  it("leaves a current .gitignore byte-identical", () => {
    const text = `dist/\n\n${BLOCK}`;
    expect(gitignoreWith(text).outputs).toEqual([{ kind: "file", path: ".gitignore", content: text, tracked: true }]);
  });

  it("does not take a longer marker for the begin marker", () => {
    const text = "# >>> @workerstack/repository\n";
    expect(gitignoreWith(text).outputs).toEqual([{ kind: "file", path: ".gitignore", content: `${text}\n${BLOCK}`, tracked: true }]);
  });

  it("fails on a begin marker with no closing marker", () => {
    expect(gitignoreWith("# >>> @workerstack/repo (generated by repo sync)\n.tmp/\n")).toEqual({
      outputs: [],
      errors: ['.gitignore: "# >>> @workerstack/repo" has no closing "# <<< @workerstack/repo"'],
    });
  });
});

describe("gitignore block by host", () => {
  const blockFor = (manifest: PackageJson, hosts: Host[]) => {
    const out = gitignore(context({ hosts, manifest })).outputs[0];
    return contentOf(out);
  };

  it("lists AGENTS.md, .mcp.json and every host dir in a consumer", () => {
    expect(blockFor({ name: "app" }, ["claude", "codex", "antigravity", "grok", "cursor"])).toBe(
      blockOf("AGENTS.md", ".mcp.json", ".agents/", ".claude/", ".codex/", ".cursor/", ".grok/"),
    );
  });

  it("lists only what the enabled hosts own", () => {
    expect(blockFor({ name: "app" }, ["claude"])).toBe(blockOf("AGENTS.md", ".mcp.json", ".claude/"));
    expect(blockFor({ name: "app" }, ["codex"])).toBe(blockOf("AGENTS.md", ".agents/skills/", ".codex/"));
    expect(blockFor({ name: "app" }, ["codex", "antigravity"])).toBe(blockOf("AGENTS.md", ".agents/", ".codex/"));
  });

  it("lists only .repo/tmp/ extra in this repo, whose trees are committed", () => {
    expect(blockFor({ name: "@workerstack/repo" }, ["claude", "codex"])).toBe(SELF_BLOCK);
  });
});

describe("trees", () => {
  it("runs no rulesync and writes nothing with no hosts", () => {
    expect(trees(context())).toEqual({ outputs: [], errors: [] });
  });

  it("turns a failed render into one error", () => {
    const result = trees(context({ hosts: ["claude"] }));
    expect(result.outputs).toEqual([]);
    expect(result.errors).toEqual([expect.stringContaining("bun install")]);
  });
});

describe("index", () => {
  const STACK_ROOT: PackageJson = { dependencies: { "@workerstack/repo": "^1.0.0" } };

  it("does nothing when the docs pack is off", () => {
    expect(index(context({ packs: ["agents"], packages: [API], files: {} }))).toEqual({ outputs: [], errors: [] });
  });

  it("creates the file with both sections when it is missing", () => {
    const ctx = context({ manifest: STACK_ROOT, packages: [WEB, API], files: PACKAGE_INDEXES });
    expect(index(ctx)).toEqual({
      outputs: [{ kind: "file", path: "references/INDEX.md", content: `# References\n\n${PACKAGES_SECTION}\n\n${REPO_STACK}\n`, tracked: true }],
      errors: [],
    });
  });

  it("writes no packages section in a single-package repo, and keeps empty stack markers", () => {
    expect(index(context()).outputs).toEqual([
      { kind: "file", path: "references/INDEX.md", content: `# References\n\n${EMPTY_STACK}\n`, tracked: true },
    ]);
  });

  it("replaces present sections in place and keeps the hand-written text around them", () => {
    const text =
      "# Docs\n\nIntro.\n\n<!-- repo:packages -->\n- stale\n<!-- /repo:packages -->\n\nMiddle.\n\n" +
      "<!-- repo:stack -->\n- stale\n<!-- /repo:stack -->\n\nFooter.\n";
    const ctx = context({
      manifest: STACK_ROOT,
      packages: [WEB, API],
      files: { ...PACKAGE_INDEXES, "references/INDEX.md": text },
    });
    expect(index(ctx).outputs).toEqual([
      {
        kind: "file",
        path: "references/INDEX.md",
        content: `# Docs\n\nIntro.\n\n${PACKAGES_SECTION}\n\nMiddle.\n\n${REPO_STACK}\n\nFooter.\n`,
        tracked: true,
      },
    ]);
  });

  it("appends absent sections at the end after a blank line", () => {
    const ctx = context({
      manifest: STACK_ROOT,
      packages: [WEB, API],
      files: { ...PACKAGE_INDEXES, "references/INDEX.md": "# Docs\n\nHand-written." },
    });
    expect(index(ctx).outputs).toEqual([
      {
        kind: "file",
        path: "references/INDEX.md",
        content: `# Docs\n\nHand-written.\n\n${PACKAGES_SECTION}\n\n${REPO_STACK}\n`,
        tracked: true,
      },
    ]);
  });

  it("describes a package by its first non-empty INDEX line and links it by name, else by dir", () => {
    const ctx = context({
      packages: [
        { dir: "libs/blank", manifest: { name: "" } },
        { dir: "libs/heading", manifest: { name: "heading" } },
      ],
      files: { "libs/blank/references/INDEX.md": "\n  \n", "libs/heading/references/INDEX.md": "  ## Sub  \n# Top\n" },
    });
    expect(contentOf(index(ctx).outputs[0])).toContain(
      "<!-- repo:packages -->\n" +
        "- [libs/blank](../libs/blank/references/INDEX.md)\n" +
        "- [heading](../libs/heading/references/INDEX.md): ## Sub\n" +
        "<!-- /repo:packages -->\n",
    );
  });

  it("fails naming each workspace package that has no references/INDEX.md", () => {
    const ctx = context({ packages: [WEB, API], files: {} });
    expect(index(ctx)).toEqual({
      outputs: [],
      errors: [
        "apps/web has no references/INDEX.md; every workspace package needs one",
        "packages/api has no references/INDEX.md; every workspace package needs one",
      ],
    });
  });

  it("lists every @workerstack/* dependency of the root and packages once, sorted", () => {
    const ctx = context({
      manifest: {
        dependencies: { "@workerstack/repo": "^1.0.0", zod: "^4.0.0" },
        devDependencies: { "@workerstack/lint": "^1.0.0" },
      },
      packages: [
        {
          dir: "packages/api",
          manifest: {
            peerDependencies: { "@workerstack/worker": "^1.0.0", "@workerstack/repo": "^1.0.0" },
            optionalDependencies: { "@workerstack/ai": "^1.0.0", "@workerstackx/no": "1.0.0" },
          },
        },
      ],
      files: { "packages/api/references/INDEX.md": "API\n" },
    });
    const link = (name: string) => `- [${name}](../node_modules/${name}/references/INDEX.md)\n`;
    expect(contentOf(index(ctx).outputs[0])).toContain(
      "<!-- repo:stack -->\n" +
        link("@workerstack/ai") +
        link("@workerstack/lint") +
        link("@workerstack/repo") +
        link("@workerstack/worker") +
        "<!-- /repo:stack -->\n",
    );
  });

  it("fails on a section opener with no closer", () => {
    const ctx = context({ files: { "references/INDEX.md": "# Docs\n\n<!-- repo:stack -->\n- stale\n" } });
    expect(index(ctx)).toEqual({
      outputs: [],
      errors: ['references/INDEX.md: "<!-- repo:stack -->" has no closing "<!-- /repo:stack -->"'],
    });
  });

  it("reports a missing package INDEX and an unclosed section together", () => {
    const ctx = context({ packages: [API], files: { "references/INDEX.md": "<!-- repo:packages -->\n" } });
    expect(index(ctx).errors).toEqual([
      "packages/api has no references/INDEX.md; every workspace package needs one",
      'references/INDEX.md: "<!-- repo:packages -->" has no closing "<!-- /repo:packages -->"',
    ]);
  });
});
