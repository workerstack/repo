const BUNFIG = '# Generated by repo sync. Do not edit.\n[install]\nlinker = "hoisted"\nauto = "disable"\n';

type Fixture = {
  hosts?: Host[];
  packs?: Pack[];
  manifest?: PackageJson;
  packages?: WorkspacePackage[];
  files?: Record<string, string>;
};

/** A sync context over in-memory files; `read` sees only `files`. */
function context({
  hosts = [],
  packs = ["agents", "docs"],
  manifest = {},
  packages = [],
  files = {},
}: Fixture = {}): SyncContext {
  return {
    root: "/repo",
    config: {
      packs,
      agents: { hosts, skills: [] },
      ...BASE_CONFIG,
    },
    workspace: { root: "/repo", manifest, packages },
    read: (rel) => files[rel] ?? null,
  };
}

/** The text of a file output. */
function contentOf(output: Output | undefined): string | undefined {
  return output?.kind === "file" ? output.content : undefined;
}

const API: WorkspacePackage = { dir: "packages/api", manifest: { name: "@acme/api" } };
const WEB: WorkspacePackage = { dir: "apps/web", manifest: { name: "web" } };
const PACKAGE_INDEXES = {
  "packages/api/references/INDEX.md": "\n\n# API worker\n\nMore.\n",
  "apps/web/references/INDEX.md": "Web app\r\n",
};
const PACKAGES_SECTION =
  "<!-- repo:packages -->\n" +
  "- [web](../apps/web/references/INDEX.md): Web app\n" +
  "- [@acme/api](../packages/api/references/INDEX.md): API worker\n" +
  "<!-- /repo:packages -->";
const REPO_STACK =
  "<!-- repo:stack -->\n" +
  "- [@workerstack/repo](../node_modules/@workerstack/repo/references/INDEX.md)\n" +
  "<!-- /repo:stack -->";
const EMPTY_STACK = "<!-- repo:stack -->\n<!-- /repo:stack -->";

describe("GENERATORS", () => {
  it("runs bunfig, index, the readme, lessons, trees, release, nightly, the release workflow, the github files, the vitest projects, turbo and rust in that order", () => {
    expect(GENERATORS).toEqual([
      ...[bunfig, index, readme, lessons, trees, release, nightly, releaseWorkflow, githubFiles],
      ...[vitestProjects, turbo, rust],
    ]);
  });
});

describe("bunfig", () => {
  it("writes the generated bunfig.toml when none exists", () => {
    expect(bunfig(context())).toEqual({
      outputs: [{ kind: "file", path: "bunfig.toml", content: BUNFIG, tracked: true, managed: "whole" }],
      errors: [],
    });
  });

  it("returns the same content when the file is current", () => {
    expect(bunfig(context({ files: { "bunfig.toml": BUNFIG } }))).toEqual({
      outputs: [{ kind: "file", path: "bunfig.toml", content: BUNFIG, tracked: true, managed: "whole" }],
      errors: [],
    });
  });

  it("owns a stale file that still starts with the generated header", () => {
    const stale = '# Generated by repo sync. Do not edit.\r\n[install]\r\nlinker = "isolated"\r\n';
    expect(bunfig(context({ files: { "bunfig.toml": stale } })).outputs).toEqual([
      { kind: "file", path: "bunfig.toml", content: BUNFIG, tracked: true, managed: "whole" },
    ]);
  });

  it("refuses a hand-written bunfig.toml", () => {
    expect(bunfig(context({ files: { "bunfig.toml": '[test]\nroot = "x"\n' } }))).toEqual({
      outputs: [],
      errors: ["bunfig.toml is hand-written; delete it so repo sync can own it"],
    });
  });
});

describe("trees", () => {
  it("writes nothing without the agents pack, whatever the hosts", () => {
    expect(trees(context({ hosts: ["claude"], packs: ["docs"] }))).toEqual({ outputs: [], errors: [] });
    expect(trees(context({ hosts: ["claude"], packs: [] }))).toEqual({ outputs: [], errors: [] });
  });

  it("writes nothing with the agents pack and no hosts", () => {
    expect(trees(context())).toEqual({ outputs: [], errors: [] });
  });

  it("turns a failed render into one error", () => {
    const result = trees(context({ hosts: ["claude"] }));
    expect(result.outputs).toEqual([]);
    expect(result.errors).toEqual([expect.stringContaining("bun install")]);
  });
});

describe("lessons", () => {
  /** A real root with a lessons dir, so the pack alone decides whether the index is written. */
  const withLessonsDir = (packs: Pack[]) => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "workerstack-lessons-"));
    try {
      fs.mkdirSync(path.join(root, ".repo", "lessons"), { recursive: true });
      return lessons({ ...context({ packs }), root });
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
  };

  it("writes nothing without the agents pack", () => {
    expect(withLessonsDir(["docs"])).toEqual({ outputs: [], errors: [] });
    expect(withLessonsDir([])).toEqual({ outputs: [], errors: [] });
  });

  it("writes the lessons index with the agents pack", () => {
    expect(withLessonsDir(["agents"]).outputs.map((o) => o.path)).toEqual([".repo/lessons/INDEX.md"]);
  });
});

describe("index", () => {
  const STACK_ROOT: PackageJson = { dependencies: { "@workerstack/repo": "^1.0.0" } };

  it("does nothing when the docs pack is off", () => {
    expect(index(context({ packs: ["agents"], packages: [API], files: {} }))).toEqual({ outputs: [], errors: [] });
  });

  it("creates the file with both sections when it is missing, then each package INDEX with an empty deps section", () => {
    const ctx = context({ manifest: STACK_ROOT, packages: [WEB, API], files: PACKAGE_INDEXES });
    const block = (path: string, content: string): Output => ({
      kind: "file",
      path,
      content,
      tracked: true,
      managed: "block",
    });
    expect(index(ctx)).toEqual({
      outputs: [
        block("references/INDEX.md", `# References\n\n${PACKAGES_SECTION}\n\n${REPO_STACK}\n`),
        block("apps/web/references/INDEX.md", "Web app\n\n<!-- repo:deps -->\n<!-- /repo:deps -->\n"),
        block(
          "packages/api/references/INDEX.md",
          "\n\n# API worker\n\nMore.\n\n<!-- repo:deps -->\n<!-- /repo:deps -->\n",
        ),
      ],
      errors: [],
    });
  });

  it("writes no packages section in a single-package repo, and keeps empty stack markers", () => {
    expect(index(context()).outputs).toEqual([
      {
        kind: "file",
        path: "references/INDEX.md",
        content: `# References\n\n${EMPTY_STACK}\n`,
        tracked: true,
        managed: "block",
      },
    ]);
  });

  it("replaces present sections in place and keeps the hand-written text around them", () => {
    const text =
      "# Docs\n\nIntro.\n\n<!-- repo:packages -->\n- stale\n<!-- /repo:packages -->\n\nMiddle.\n\n" +
      "<!-- repo:stack -->\n- stale\n<!-- /repo:stack -->\n\nFooter.\n";
    const ctx = context({
      manifest: STACK_ROOT,
      packages: [WEB, API],
      files: { ...PACKAGE_INDEXES, "references/INDEX.md": text },
    });
    expect(index(ctx).outputs.slice(0, 1)).toEqual([
      {
        kind: "file",
        path: "references/INDEX.md",
        content: `# Docs\n\nIntro.\n\n${PACKAGES_SECTION}\n\nMiddle.\n\n${REPO_STACK}\n\nFooter.\n`,
        tracked: true,
        managed: "block",
      },
    ]);
  });

  it("appends absent sections at the end after a blank line", () => {
    const ctx = context({
      manifest: STACK_ROOT,
      packages: [WEB, API],
      files: { ...PACKAGE_INDEXES, "references/INDEX.md": "# Docs\n\nHand-written." },
    });
    expect(index(ctx).outputs.slice(0, 1)).toEqual([
      {
        kind: "file",
        path: "references/INDEX.md",
        content: `# Docs\n\nHand-written.\n\n${PACKAGES_SECTION}\n\n${REPO_STACK}\n`,
        tracked: true,
        managed: "block",
      },
    ]);
  });

  it("describes a package by its first non-empty INDEX line and links it by name, else by dir", () => {
    const ctx = context({
      packages: [
        { dir: "libs/blank", manifest: { name: "" } },
        { dir: "libs/heading", manifest: { name: "heading" } },
      ],
      files: { "libs/blank/references/INDEX.md": "\n  \n", "libs/heading/references/INDEX.md": "  ## Sub  \n# Top\n" },
    });
    expect(contentOf(index(ctx).outputs[0])).toContain(
      "<!-- repo:packages -->\n" +
        "- [libs/blank](../libs/blank/references/INDEX.md)\n" +
        "- [heading](../libs/heading/references/INDEX.md): ## Sub\n" +
        "<!-- /repo:packages -->\n",
    );
  });

  it("fails naming each workspace package that has no references/INDEX.md", () => {
    const ctx = context({ packages: [WEB, API], files: {} });
    expect(index(ctx)).toEqual({
      outputs: [],
      errors: [
        "apps/web has no references/INDEX.md; every workspace package needs one",
        "packages/api has no references/INDEX.md; every workspace package needs one",
      ],
    });
  });

  it("lists every @workerstack/* dependency of the root and packages once, sorted", () => {
    const ctx = context({
      manifest: {
        dependencies: { "@workerstack/repo": "^1.0.0", zod: "^4.0.0" },
        devDependencies: { "@workerstack/lint": "^1.0.0" },
      },
      packages: [
        {
          dir: "packages/api",
          manifest: {
            peerDependencies: { "@workerstack/worker": "^1.0.0", "@workerstack/repo": "^1.0.0" },
            optionalDependencies: { "@workerstack/ai": "^1.0.0", "@workerstackx/no": "1.0.0" },
          },
        },
      ],
      files: { "packages/api/references/INDEX.md": "API\n" },
    });
    const link = (name: string) => `- [${name}](../node_modules/${name}/references/INDEX.md)\n`;
    expect(contentOf(index(ctx).outputs[0])).toContain(
      "<!-- repo:stack -->\n" +
        link("@workerstack/ai") +
        link("@workerstack/lint") +
        link("@workerstack/repo") +
        link("@workerstack/worker") +
        "<!-- /repo:stack -->\n",
    );
  });

  it("fails on a section opener with no closer", () => {
    const ctx = context({ files: { "references/INDEX.md": "# Docs\n\n<!-- repo:stack -->\n- stale\n" } });
    expect(index(ctx)).toEqual({
      outputs: [],
      errors: ['references/INDEX.md: "<!-- repo:stack -->" has no closing "<!-- /repo:stack -->"'],
    });
  });

  it("reports a missing package INDEX and an unclosed section together", () => {
    const ctx = context({ packages: [API], files: { "references/INDEX.md": "<!-- repo:packages -->\n" } });
    expect(index(ctx).errors).toEqual([
      "packages/api has no references/INDEX.md; every workspace package needs one",
      'references/INDEX.md: "<!-- repo:packages -->" has no closing "<!-- /repo:packages -->"',
    ]);
  });
});

describe("index repo:available", () => {
  const entry = (name: string, text: string) => `- [${name}](https://www.npmjs.com/package/${name}): ${text}`;
  const INDEX_TEXT = [
    entry("@workerstack/repo", "Workflows"),
    entry("@workerstack/system", "OS"),
    entry("@workerstack/testing", "Tests"),
    entry("@acme/api", "Own"),
    entry("@workerstack/root", "Root"),
    entry("@workerstack/database", "DB"),
  ].join("\n");
  const files = { [AVAILABLE_INDEX_PATH]: `${INDEX_TEXT}\n` };

  it("lists the uninstalled packages after repo:stack, minus every installed, root and workspace name", () => {
    const ctx = context({
      manifest: { name: "@workerstack/root", devDependencies: { "@workerstack/repo": "^1.0.0" } },
      packages: [{ ...API, manifest: { ...API.manifest, dependencies: { "@workerstack/testing": "^1.0.0" } } }],
      files: { ...files, ...PACKAGE_INDEXES },
    });
    expect(contentOf(index(ctx).outputs[0])).toContain(
      "<!-- /repo:stack -->\n\n<!-- repo:available -->\n" +
        `${entry("@workerstack/system", "OS")}\n${entry("@workerstack/database", "DB")}\n` +
        "<!-- /repo:available -->\n",
    );
  });

  it("writes no section when no index is installed", () => {
    expect(contentOf(index(context()).outputs[0])).not.toContain("repo:available");
  });

  it("writes nothing with the docs pack off", () => {
    expect(index(context({ packs: ["agents"], files }))).toEqual({ outputs: [], errors: [] });
  });
});

describe("index repo:deps", () => {
  const pkg = (dir: string, name: string, deps: Partial<PackageJson> = {}): WorkspacePackage => ({
    dir,
    manifest: { name, ...deps },
  });
  const WEB_PKG = pkg("packages/web", "@acme/web", {
    dependencies: { "@acme/api": "1.0.0", react: "19.0.0", "@workerstack/ui": "1.0.0" },
    devDependencies: { "@acme/core": "1.0.0", "@workerstack/lint": "1.0.0", "@workerstack/shared": "1.0.0" },
    peerDependencies: { "@acme/api": "1.0.0" },
    optionalDependencies: { "@workerstack/ai": "1.0.0" },
  });
  const files = {
    "packages/web/references/INDEX.md": "# Web\n",
    "packages/api/references/INDEX.md": "# Api\n",
    "packages/core/references/INDEX.md": "# Core\n",
    "packages/shared/references/INDEX.md": "# Shared\n",
  };
  const packages = [
    WEB_PKG,
    pkg("packages/api", "@acme/api"),
    pkg("packages/core", "@acme/core"),
    pkg("packages/shared", "@workerstack/shared"),
  ];
  const depsOf = (rel: string, ctx = context({ packages, files })) => {
    const content = contentOf(index(ctx).outputs.find((o) => o.path === rel));
    return content?.split("<!-- repo:deps -->\n")[1]?.split("<!-- /repo:deps -->")[0];
  };

  it("links the INDEX of each workspace dependency first, then each other @workerstack/* one, both sorted and deduped", () => {
    expect(depsOf("packages/web/references/INDEX.md")).toBe(
      "- [@acme/api](../../api/references/INDEX.md)\n" +
        "- [@acme/core](../../core/references/INDEX.md)\n" +
        "- [@workerstack/shared](../../shared/references/INDEX.md)\n" +
        "- [@workerstack/ai](../../../node_modules/@workerstack/ai/references/INDEX.md)\n" +
        "- [@workerstack/lint](../../../node_modules/@workerstack/lint/references/INDEX.md)\n" +
        "- [@workerstack/ui](../../../node_modules/@workerstack/ui/references/INDEX.md)\n",
    );
  });

  it("gives a package with no such dependency an empty section, and replaces a stale one in place", () => {
    expect(depsOf("packages/api/references/INDEX.md")).toBe("");
    const stale = {
      ...files,
      "packages/web/references/INDEX.md": "# Web\n\n<!-- repo:deps -->\n- stale\n<!-- /repo:deps -->\n\nTail.\n",
    };
    const content = contentOf(
      index(context({ packages, files: stale })).outputs.find((o) => o.path === "packages/web/references/INDEX.md"),
    );
    expect(content).toMatch(/^# Web\n\n<!-- repo:deps -->\n- \[@acme\/api\]/);
    expect(content).toMatch(/<!-- \/repo:deps -->\n\nTail\.\n$/);
    expect(content).not.toContain("stale");
  });

  it("fails on an unclosed deps section in a package INDEX", () => {
    const broken = { ...files, "packages/api/references/INDEX.md": "# Api\n<!-- repo:deps -->\n" };
    expect(index(context({ packages, files: broken }))).toEqual({
      outputs: [],
      errors: ['packages/api/references/INDEX.md: "<!-- repo:deps -->" has no closing "<!-- /repo:deps -->"'],
    });
  });
});
