/** What the generator plans; sync stamps its header on line 1. */
const BUNFIG = '[install]\nlinker = "hoisted"\nauto = "disable"\n';
const HEADER = "# @generated by @workerstack/repo";

type Fixture = {
  hosts?: Host[];
  packs?: Pack[];
  manifest?: PackageJson;
  packages?: WorkspacePackage[];
  files?: Record<string, string>;
};

/** A sync context over in-memory files; `read` sees only `files`. */
function context({
  hosts = [],
  packs = ["agents", "docs"],
  manifest = {},
  packages = [],
  files = {},
}: Fixture = {}): SyncContext {
  return {
    config: {
      agents: { hosts, skills: [] },
      packs,
      ...BASE_CONFIG,
    },
    read: (rel) => files[rel] ?? null,
    root: "/repo",
    workspace: { manifest, packages, root: "/repo" },
  };
}

/** The text of a file output. */
function contentOf(output: Output | undefined): string | undefined {
  return output?.kind === "file" ? output.content : undefined;
}

const API: WorkspacePackage = { dir: "packages/api", manifest: { name: "@acme/api" } };
const WEB: WorkspacePackage = { dir: "apps/web", manifest: { name: "web" } };
const PACKAGE_INDEXES = {
  "apps/web/references/INDEX.md": "Web app\r\n",
  "packages/api/references/INDEX.md": "\n\n# API worker\n\nMore.\n",
};
/** The markdown region `name` holding `body`, as sync writes it, with no trailing newline. */
const section = (name: string, body: string) =>
  `<!-- repo:${name} ${regionHash(body)} -->\n${body === "" ? "" : `${body}\n`}<!-- /repo:${name} -->`;
const PACKAGES_SECTION = section(
  "packages",
  "- [web](../apps/web/references/INDEX.md): Web app\n- [@acme/api](../packages/api/references/INDEX.md): API worker",
);
const REPO_STACK = section("stack", "- [@workerstack/repo](../node_modules/@workerstack/repo/references/INDEX.md)");
const EMPTY_STACK = section("stack", "");
const EMPTY_DEPS = section("deps", "");
/** The repairs the index generator reports on `rel`. */
const repairsOf = (ctx: SyncContext, rel: string) => {
  const found = index(ctx).outputs.find((output) => output.path === rel);
  return found?.kind === "file" ? found.repairs : undefined;
};

describe("GENERATORS", () => {
  it("runs bunfig, index, the readme, lessons, trees, release, nightly, the release workflow, the github files, the vitest projects, turbo and rust in that order", () => {
    expect(GENERATORS).toStrictEqual([
      bunfig,
      index,
      readme,
      lessons,
      trees,
      release,
      nightly,
      releaseWorkflow,
      githubFiles,
      vitestProjects,
      turbo,
      rust,
    ]);
  });
});

describe("bunfig", () => {
  it("writes the generated bunfig.toml when none exists", () => {
    expect(bunfig(context())).toStrictEqual({
      errors: [],
      outputs: [{ content: BUNFIG, kind: "file", managed: "whole", path: "bunfig.toml", tracked: true }],
    });
  });

  it("returns the same content when the file is current", () => {
    expect(bunfig(context({ files: { "bunfig.toml": `${HEADER}\n${BUNFIG}` } }))).toStrictEqual({
      errors: [],
      outputs: [{ content: BUNFIG, kind: "file", managed: "whole", path: "bunfig.toml", tracked: true }],
    });
  });

  it("owns a stale file that still starts with a legacy header", () => {
    const stale = '# Generated by repo sync. Do not edit.\r\n[install]\r\nlinker = "isolated"\r\n';
    expect(bunfig(context({ files: { "bunfig.toml": stale } })).outputs).toStrictEqual([
      { content: BUNFIG, kind: "file", managed: "whole", path: "bunfig.toml", tracked: true },
    ]);
  });

  it("refuses a hand-written bunfig.toml", () => {
    expect(bunfig(context({ files: { "bunfig.toml": '[test]\nroot = "x"\n' } }))).toStrictEqual({
      errors: ["bunfig.toml is hand-written; delete it so repo sync can own it"],
      outputs: [],
    });
  });
});

describe("trees", () => {
  it("writes nothing without the agents pack, whatever the hosts", () => {
    expect(trees(context({ hosts: ["claude"], packs: ["docs"] }))).toStrictEqual({ errors: [], outputs: [] });
    expect(trees(context({ hosts: ["claude"], packs: [] }))).toStrictEqual({ errors: [], outputs: [] });
  });

  it("writes nothing with the agents pack and no hosts", () => {
    expect(trees(context())).toStrictEqual({ errors: [], outputs: [] });
  });

  it("turns a failed render into one error", () => {
    const result = trees(context({ hosts: ["claude"] }));
    expect(result.outputs).toStrictEqual([]);
    expect(result.errors).toStrictEqual([expect.stringContaining("bun install")]);
  });
});

describe("lessons", () => {
  /** A real root with a lessons dir, so the pack alone decides whether the index is written. */
  const withLessonsDir = (packs: Pack[]) => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "workerstack-lessons-"));
    try {
      fs.mkdirSync(path.join(root, ".repo", "lessons"), { recursive: true });
      return lessons({ ...context({ packs }), root });
    } finally {
      fs.rmSync(root, { force: true, recursive: true });
    }
  };

  it("writes nothing without the agents pack", () => {
    expect(withLessonsDir(["docs"])).toStrictEqual({ errors: [], outputs: [] });
    expect(withLessonsDir([])).toStrictEqual({ errors: [], outputs: [] });
  });

  it("writes the lessons index with the agents pack", () => {
    expect(withLessonsDir(["agents"]).outputs.map((o) => o.path)).toStrictEqual([".repo/lessons/INDEX.md"]);
  });
});

describe("index", () => {
  const STACK_ROOT: PackageJson = { dependencies: { "@workerstack/repo": "^1.0.0" } };

  it("does nothing when the docs pack is off", () => {
    expect(index(context({ files: {}, packages: [API], packs: ["agents"] }))).toStrictEqual({
      errors: [],
      outputs: [],
    });
  });

  it("creates the file with both sections when it is missing, then each package INDEX with an empty deps section", () => {
    const ctx = context({ files: PACKAGE_INDEXES, manifest: STACK_ROOT, packages: [WEB, API] });
    const block = (path: string, content: string): Output => ({
      content,
      kind: "file",
      managed: "block",
      path,
      tracked: true,
    });
    expect(index(ctx)).toStrictEqual({
      errors: [],
      outputs: [
        block("references/INDEX.md", `# References\n\n${PACKAGES_SECTION}\n\n${REPO_STACK}\n`),
        block("apps/web/references/INDEX.md", `Web app\n\n${EMPTY_DEPS}\n`),
        block("packages/api/references/INDEX.md", `\n\n# API worker\n\nMore.\n\n${EMPTY_DEPS}\n`),
      ],
    });
  });

  it("writes no packages section in a single-package repo, and keeps empty stack markers", () => {
    expect(index(context()).outputs).toStrictEqual([
      {
        content: `# References\n\n${EMPTY_STACK}\n`,
        kind: "file",
        managed: "block",
        path: "references/INDEX.md",
        tracked: true,
      },
    ]);
  });

  it("hashes unhashed sections in place in one pass, one line each, and keeps the hand-written text around them", () => {
    const text =
      "# Docs\n\nIntro.\n\n<!-- repo:packages -->\n- stale\n<!-- /repo:packages -->\n\nMiddle.\n\n" +
      "<!-- repo:stack -->\n- stale\n<!-- /repo:stack -->\n\nFooter.\n";
    const files = { ...PACKAGE_INDEXES, "references/INDEX.md": text };
    const ctx = context({ files, manifest: STACK_ROOT, packages: [WEB, API] });
    const content = `# Docs\n\nIntro.\n\n${PACKAGES_SECTION}\n\nMiddle.\n\n${REPO_STACK}\n\nFooter.\n`;
    expect(index(ctx).outputs.slice(0, 1)).toStrictEqual([
      {
        content,
        kind: "file",
        managed: "block",
        path: "references/INDEX.md",
        repairs: ["added the hash to repo:packages", "added the hash to repo:stack"],
        tracked: true,
      },
    ]);
    const again = context({
      files: { ...files, "references/INDEX.md": content },
      manifest: STACK_ROOT,
      packages: [WEB, API],
    });
    expect([contentOf(index(again).outputs[0]), repairsOf(again, "references/INDEX.md")]).toStrictEqual([
      content,
      undefined,
    ]);
  });

  it("appends absent sections at the end after a blank line", () => {
    const ctx = context({
      files: { ...PACKAGE_INDEXES, "references/INDEX.md": "# Docs\n\nHand-written." },
      manifest: STACK_ROOT,
      packages: [WEB, API],
    });
    expect(index(ctx).outputs.slice(0, 1)).toStrictEqual([
      {
        content: `# Docs\n\nHand-written.\n\n${PACKAGES_SECTION}\n\n${REPO_STACK}\n`,
        kind: "file",
        managed: "block",
        path: "references/INDEX.md",
        tracked: true,
      },
    ]);
  });

  it("describes a package by its first non-empty INDEX line and links it by name, else by dir", () => {
    const ctx = context({
      files: { "libs/blank/references/INDEX.md": "\n  \n", "libs/heading/references/INDEX.md": "  ## Sub  \n# Top\n" },
      packages: [
        { dir: "libs/blank", manifest: { name: "" } },
        { dir: "libs/heading", manifest: { name: "heading" } },
      ],
    });
    expect(contentOf(index(ctx).outputs[0])).toContain(
      section(
        "packages",
        "- [libs/blank](../libs/blank/references/INDEX.md)\n- [heading](../libs/heading/references/INDEX.md): ## Sub",
      ),
    );
  });

  it("fails naming each workspace package that has no references/INDEX.md", () => {
    const ctx = context({ files: {}, packages: [WEB, API] });
    expect(index(ctx)).toStrictEqual({
      errors: [
        "apps/web has no references/INDEX.md; every workspace package needs one",
        "packages/api has no references/INDEX.md; every workspace package needs one",
      ],
      outputs: [],
    });
  });

  it("lists every @workerstack/* dependency of the root and packages once, sorted", () => {
    const ctx = context({
      files: { "packages/api/references/INDEX.md": "API\n" },
      manifest: {
        dependencies: { "@workerstack/repo": "^1.0.0", zod: "^4.0.0" },
        devDependencies: { "@workerstack/lint": "^1.0.0" },
      },
      packages: [
        {
          dir: "packages/api",
          manifest: {
            optionalDependencies: { "@workerstack/ai": "^1.0.0", "@workerstackx/no": "1.0.0" },
            peerDependencies: { "@workerstack/repo": "^1.0.0", "@workerstack/worker": "^1.0.0" },
          },
        },
      ],
    });
    const link = (name: string) => `- [${name}](../node_modules/${name}/references/INDEX.md)`;
    const names = ["@workerstack/ai", "@workerstack/lint", "@workerstack/repo", "@workerstack/worker"];
    expect(contentOf(index(ctx).outputs[0])).toContain(section("stack", names.map(link).join("\n")));
  });

  it("closes a section opener with no closer, keeping the user's line below it, instead of failing", () => {
    const ctx = context({ files: { "references/INDEX.md": "# Docs\n\n<!-- repo:stack -->\n- mine\n" } });
    expect(index(ctx)).toStrictEqual({
      errors: [],
      outputs: [
        {
          content: `# Docs\n\n${EMPTY_STACK}\n- mine\n`,
          kind: "file",
          managed: "block",
          path: "references/INDEX.md",
          repairs: ["closed repo:stack"],
          tracked: true,
        },
      ],
    });
  });

  it("repairs a stray closer and a duplicate section, one line each", () => {
    const text = `# Docs\n\n<!-- /repo:stack -->\n\n${EMPTY_STACK}\n\n${EMPTY_STACK}\n`;
    const ctx = context({ files: { "references/INDEX.md": text } });
    expect(contentOf(index(ctx).outputs[0])).toBe(`# Docs\n\n${EMPTY_STACK}\n`);
    expect(repairsOf(ctx, "references/INDEX.md")).toStrictEqual([
      "dropped 1 extra repo:stack",
      "dropped 1 stray marker of repo:stack",
    ]);
  });

  it("still fails on a missing package INDEX while it repairs an unclosed section", () => {
    const ctx = context({ files: { "references/INDEX.md": "<!-- repo:packages -->\n" }, packages: [API] });
    expect(index(ctx)).toStrictEqual({
      errors: ["packages/api has no references/INDEX.md; every workspace package needs one"],
      outputs: [],
    });
  });
});

describe("index repo:available", () => {
  const entry = (name: string, text: string) => `- [${name}](https://www.npmjs.com/package/${name}): ${text}`;
  const INDEX_TEXT = [
    entry("@workerstack/repo", "Workflows"),
    entry("@workerstack/system", "OS"),
    entry("@workerstack/testing", "Tests"),
    entry("@acme/api", "Own"),
    entry("@workerstack/root", "Root"),
    entry("@workerstack/database", "DB"),
  ].join("\n");
  const files = { [AVAILABLE_INDEX_PATH]: `${INDEX_TEXT}\n` };

  it("lists the uninstalled packages after repo:stack, minus every installed, root and workspace name", () => {
    const ctx = context({
      files: { ...files, ...PACKAGE_INDEXES },
      manifest: { devDependencies: { "@workerstack/repo": "^1.0.0" }, name: "@workerstack/root" },
      packages: [{ ...API, manifest: { ...API.manifest, dependencies: { "@workerstack/testing": "^1.0.0" } } }],
    });
    expect(contentOf(index(ctx).outputs[0])).toContain(
      `<!-- /repo:stack -->\n\n${section("available", `${entry("@workerstack/system", "OS")}\n${entry("@workerstack/database", "DB")}`)}\n`,
    );
  });

  it("writes no section when no index is installed", () => {
    expect(contentOf(index(context()).outputs[0])).not.toContain("repo:available");
  });

  it("writes nothing with the docs pack off", () => {
    expect(index(context({ files, packs: ["agents"] }))).toStrictEqual({ errors: [], outputs: [] });
  });
});

describe("index repo:deps", () => {
  const pkg = (dir: string, name: string, deps: Partial<PackageJson> = {}): WorkspacePackage => ({
    dir,
    manifest: { name, ...deps },
  });
  const WEB_PKG = pkg("packages/web", "@acme/web", {
    dependencies: { "@acme/api": "1.0.0", "@workerstack/ui": "1.0.0", react: "19.0.0" },
    devDependencies: { "@acme/core": "1.0.0", "@workerstack/lint": "1.0.0", "@workerstack/shared": "1.0.0" },
    optionalDependencies: { "@workerstack/ai": "1.0.0" },
    peerDependencies: { "@acme/api": "1.0.0" },
  });
  const files = {
    "packages/api/references/INDEX.md": "# Api\n",
    "packages/core/references/INDEX.md": "# Core\n",
    "packages/shared/references/INDEX.md": "# Shared\n",
    "packages/web/references/INDEX.md": "# Web\n",
  };
  const packages = [
    WEB_PKG,
    pkg("packages/api", "@acme/api"),
    pkg("packages/core", "@acme/core"),
    pkg("packages/shared", "@workerstack/shared"),
  ];
  const depsOf = (rel: string, ctx = context({ files, packages })) => {
    const content = contentOf(index(ctx).outputs.find((o) => o.path === rel));
    return /<!-- repo:deps [\da-f]+ -->\n([\s\S]*?)<!-- \/repo:deps -->/.exec(content ?? "")?.[1];
  };

  it("links the INDEX of each workspace dependency first, then each other @workerstack/* one, both sorted and deduped", () => {
    expect(depsOf("packages/web/references/INDEX.md")).toBe(
      "- [@acme/api](../../api/references/INDEX.md)\n" +
        "- [@acme/core](../../core/references/INDEX.md)\n" +
        "- [@workerstack/shared](../../shared/references/INDEX.md)\n" +
        "- [@workerstack/ai](../../../node_modules/@workerstack/ai/references/INDEX.md)\n" +
        "- [@workerstack/lint](../../../node_modules/@workerstack/lint/references/INDEX.md)\n" +
        "- [@workerstack/ui](../../../node_modules/@workerstack/ui/references/INDEX.md)\n",
    );
  });

  it("gives a package with no such dependency an empty section, and replaces a stale one in place", () => {
    expect(depsOf("packages/api/references/INDEX.md")).toBe("");
    const stale = {
      ...files,
      "packages/web/references/INDEX.md": "# Web\n\n<!-- repo:deps -->\n- stale\n<!-- /repo:deps -->\n\nTail.\n",
    };
    const content = contentOf(
      index(context({ files: stale, packages })).outputs.find((o) => o.path === "packages/web/references/INDEX.md"),
    );
    expect(content).toMatch(/^# Web\n\n<!-- repo:deps [\da-f]{8} -->\n- \[@acme\/api\]/);
    expect(content).toMatch(/<!-- \/repo:deps -->\n\nTail\.\n$/);
    expect(content).not.toContain("stale");
  });

  it("closes an unclosed deps section in a package INDEX and names that INDEX", () => {
    const broken = { ...files, "packages/api/references/INDEX.md": "# Api\n<!-- repo:deps -->\n" };
    const ctx = context({ files: broken, packages });
    expect(index(ctx).errors).toStrictEqual([]);
    expect(contentOf(index(ctx).outputs.find((o) => o.path === "packages/api/references/INDEX.md"))).toBe(
      `# Api\n${EMPTY_DEPS}\n`,
    );
    expect(repairsOf(ctx, "packages/api/references/INDEX.md")).toStrictEqual(["closed repo:deps"]);
    expect(repairsOf(ctx, "packages/web/references/INDEX.md")).toBeUndefined();
  });
});
