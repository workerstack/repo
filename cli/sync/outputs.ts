import type { ResolvedConfig } from "../config.ts";
import type { Workspace } from "./workspace.ts";

/** One committed file repo sync owns, at a root-relative POSIX path. */
export type Output = { path: string; content: string };
/** What a generator sees; `read` returns a root-relative file's text, or null when it is missing. */
export type SyncContext = {
  root: string;
  config: ResolvedConfig;
  workspace: Workspace;
  read(rel: string): string | null;
};
/** Computes outputs from the context alone; it never writes, so sync can validate everything first. */
export type Generator = (ctx: SyncContext) => { outputs: Output[]; errors: string[] };
export type MergeResult = { ok: true; text: string } | { ok: false; error: string };

const BUNFIG_PATH = "bunfig.toml";
const BUNFIG_HEADER = "# Generated by repo sync. Do not edit.";
const BUNFIG = `${BUNFIG_HEADER}\n[install]\nlinker = "hoisted"\n`;

const GITIGNORE_PATH = ".gitignore";
const GITIGNORE_BEGIN = "# >>> @workerstack/repo";
const GITIGNORE_END = "# <<< @workerstack/repo";
const GITIGNORE_BODY = ".tmp/\n.worktrees/";
const BLOCK_LABEL = "(generated by repo sync)";

const INDEX_PATH = "references/INDEX.md";
const INDEX_NEW = "# References\n";
const STACK_SCOPE = "@workerstack/";
const DEPENDENCY_FIELDS = ["dependencies", "devDependencies", "peerDependencies", "optionalDependencies"] as const;

/** bunfig.toml, refusing to replace one that lacks the generated header. */
export const bunfig: Generator = (ctx) => {
  const existing = ctx.read(BUNFIG_PATH);
  if (existing !== null && lines(existing)[0] !== BUNFIG_HEADER) {
    return { outputs: [], errors: [`${BUNFIG_PATH} is hand-written; delete it so repo sync can own it`] };
  }
  return { outputs: [{ path: BUNFIG_PATH, content: BUNFIG }], errors: [] };
};

/** The managed block in .gitignore; lines outside it stay as written. */
export const gitignore: Generator = (ctx) => {
  const merged = mergeBlock(ctx.read(GITIGNORE_PATH) ?? "", GITIGNORE_BEGIN, GITIGNORE_END, GITIGNORE_BODY);
  if (!merged.ok) return { outputs: [], errors: [`${GITIGNORE_PATH}: ${merged.error}`] };
  return { outputs: [{ path: GITIGNORE_PATH, content: merged.text }], errors: [] };
};

/** The repo:packages and repo:stack sections of references/INDEX.md, under the docs pack. */
export const index: Generator = (ctx) => {
  if (!ctx.config.packs.includes("docs")) return { outputs: [], errors: [] };

  const errors: string[] = [];
  const sections: [name: string, body: string][] = [];
  const { packages } = ctx.workspace;
  if (packages.length > 0) {
    const entries: string[] = [];
    for (const { dir, manifest } of packages) {
      const text = ctx.read(`${dir}/${INDEX_PATH}`);
      if (text === null) {
        errors.push(`${dir} has no ${INDEX_PATH}; every workspace package needs one`);
        continue;
      }
      const title = lines(text)
        .map((line) => line.trim())
        .find((line) => line !== "");
      const description = title === undefined ? "" : `: ${title.replace(/^# /, "")}`;
      entries.push(`- [${manifest.name || dir}](../${dir}/${INDEX_PATH})${description}`);
    }
    sections.push(["packages", entries.join("\n")]);
  }
  const stack = stackNames(ctx.workspace).map((name) => `- [${name}](../node_modules/${name}/${INDEX_PATH})`);
  sections.push(["stack", stack.join("\n")]);

  let text = ctx.read(INDEX_PATH) ?? INDEX_NEW;
  for (const [name, body] of sections) {
    const merged = mergeSection(text, name, body);
    if (merged.ok) text = merged.text;
    else errors.push(`${INDEX_PATH}: ${merged.error}`);
  }
  if (errors.length > 0) return { outputs: [], errors };
  return { outputs: [{ path: INDEX_PATH, content: text }], errors: [] };
};

/** Every generator, in the order sync runs and reports them. */
export const GENERATORS: readonly Generator[] = [bunfig, gitignore, index];

/**
 * Replaces the lines from the first line that is `begin` (or `begin` plus a label) through the next `end` line
 * with `begin (generated by repo sync)`, `body` and `end`, or appends that block after a blank line.
 */
export function mergeBlock(text: string, begin: string, end: string, body: string): MergeResult {
  const isBegin = (line: string) => line === begin || line.startsWith(`${begin} `);
  return merge(text, isBegin, `${begin} ${BLOCK_LABEL}`, begin, end, body);
}

/** Replaces or appends the `<!-- repo:<name> -->` … `<!-- /repo:<name> -->` section with `body`. */
export function mergeSection(text: string, name: string, body: string): MergeResult {
  const open = `<!-- repo:${name} -->`;
  return merge(text, (line) => line === open, open, open, `<!-- /repo:${name} -->`, body);
}

function merge(
  text: string,
  isOpen: (line: string) => boolean,
  open: string,
  marker: string,
  close: string,
  body: string,
): MergeResult {
  const block = [open, ...(body === "" ? [] : lines(body)), close];
  const all = lines(text);
  // Markers match with trailing whitespace ignored; every other line is kept as written.
  const start = all.findIndex((line) => isOpen(line.trimEnd()));
  if (start === -1) {
    return { ok: true, text: text.trim() === "" ? finish(block) : `${finish(all)}\n${finish(block)}` };
  }
  const stop = all.findIndex((line, at) => at > start && line.trimEnd() === close);
  if (stop === -1) return { ok: false, error: `${JSON.stringify(marker)} has no closing ${JSON.stringify(close)}` };
  return { ok: true, text: finish([...all.slice(0, start), ...block, ...all.slice(stop + 1)]) };
}

/** LF-joined lines ending in exactly one newline. */
function finish(parts: string[]): string {
  return `${parts.join("\n").replace(/\n+$/, "")}\n`;
}

function lines(text: string): string[] {
  return text.split(/\r?\n/);
}

/** Every `@workerstack/*` dependency name of the root and its packages, deduped and sorted. */
function stackNames(workspace: Workspace): string[] {
  const names = new Set<string>();
  for (const manifest of [workspace.manifest, ...workspace.packages.map((pkg) => pkg.manifest)]) {
    for (const field of DEPENDENCY_FIELDS) {
      for (const name of Object.keys(manifest[field] ?? {})) if (name.startsWith(STACK_SCOPE)) names.add(name);
    }
  }
  return [...names].sort();
}
