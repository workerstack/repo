import { describe, expect, it } from "vitest";
import { parse as parseYaml } from "yaml";
import { z } from "zod";

import { context } from "../__fixtures__/release-context.ts";
import type { Pack } from "../config.ts";
import type { PackageJson } from "../sync/workspace.ts";
import { githubFiles } from "./github-files.ts";
import { hasOwnedHeader, stamp } from "./header.ts";
import { GENERATORS, type Output, type SyncContext } from "./outputs.ts";

const MD_HEADER = "<!-- @generated by @workerstack/repo -->";
const YML_HEADER = "# @generated by @workerstack/repo";
const PATHS = [
  "SECURITY.md",
  "CONTRIBUTING.md",
  ".github/CODEOWNERS",
  ".github/PULL_REQUEST_TEMPLATE.md",
  ".github/ISSUE_TEMPLATE/bug_report.yml",
  ".github/ISSUE_TEMPLATE/config.yml",
];
const FORM = ".github/ISSUE_TEMPLATE/bug_report.yml";
const CHOOSER = ".github/ISSUE_TEMPLATE/config.yml";
const ADVISORIES = "https://github.com/acme/app/security/advisories/new";
const PUBLIC: PackageJson = { name: "@acme/app", private: false };
const PACKAGE_JSON = JSON.stringify({ repository: { type: "git", url: "git+https://github.com/acme/app.git" } });

/** GitHub's issue form rules: top-level name and description, optional labels, a body of known item types. */
const ITEM = z.object({
  attributes: z.object({ label: z.string().optional() }).passthrough(),
  id: z.string().optional(),
  type: z.enum(["markdown", "input", "textarea", "dropdown", "checkboxes"]),
});
const FORM_SCHEMA = z.object({
  body: z.array(ITEM).min(1),
  description: z.string(),
  labels: z.array(z.string()).optional(),
  name: z.string(),
});
const CHOOSER_SCHEMA = z.strictObject({
  blank_issues_enabled: z.literal(false),
  contact_links: z.array(z.strictObject({ about: z.string(), name: z.string(), url: z.string() })),
});

type Setup = { packs?: Pack[]; manifest?: PackageJson; files?: Record<string, string>; owner?: boolean };

function make(setup: Setup = {}): SyncContext {
  const { packs = ["release"], manifest = PUBLIC, files = { "package.json": PACKAGE_JSON }, owner = true } = setup;
  const ctx = context(packs, manifest, files);
  return owner ? { ...ctx, config: { ...ctx.config, owner: { github: "ann", name: "Ann Acme" } } } : ctx;
}

function contentOf(outputs: Output[], path: string): string {
  const found = outputs.find((output) => output.path === path);
  if (found?.kind !== "file") throw new Error(`no file ${path}`);
  return found.content;
}

describe("githubFiles output", () => {
  it("is registered", () => {
    expect(GENERATORS).toContain(githubFiles);
  });

  it("writes the six tracked whole files, which sync heads in each one's comment syntax", () => {
    const { outputs, errors } = githubFiles(make());
    expect(errors).toStrictEqual([]);
    expect(outputs.map((output) => output.path)).toStrictEqual(PATHS);
    for (const output of outputs) {
      expect(output).toMatchObject({ kind: "file", managed: "whole", tracked: true });
      const header = output.path.endsWith(".md") ? MD_HEADER : YML_HEADER;
      const content = contentOf(outputs, output.path);
      expect(hasOwnedHeader(content), output.path).toBe(false);
      expect(stamp(output.path, content).startsWith(`${header}\n`), output.path).toBe(true);
    }
  });

  it("fills the owner and the repository in", () => {
    const { outputs } = githubFiles(make());
    expect(contentOf(outputs, ".github/CODEOWNERS")).toBe("* @ann\n");
    expect(contentOf(outputs, "SECURITY.md")).toContain(ADVISORIES);
    expect(contentOf(outputs, "SECURITY.md")).toMatch(/not .*public issue/i);
    const contribution = contentOf(outputs, "CONTRIBUTING.md");
    for (const text of ["bun install", "bun repo ci", "Conventional Commits"]) expect(contribution).toContain(text);
    expect(contentOf(outputs, ".github/PULL_REQUEST_TEMPLATE.md")).toContain("- [ ] ");
  });
});

describe("githubFiles repository and rewrite", () => {
  it("reads a repository given as a string", () => {
    const files = { "package.json": '{"repository":"github:acme/app"}' };
    expect(contentOf(githubFiles(make({ files })).outputs, "SECURITY.md")).toContain(ADVISORIES);
  });

  it("rewrites its own files, as sync stamped them", () => {
    const first = githubFiles(make()).outputs;
    const files: Record<string, string> = { "package.json": PACKAGE_JSON };
    for (const output of first) if (output.kind === "file") files[output.path] = stamp(output.path, output.content);
    expect(githubFiles(make({ files })).outputs).toStrictEqual(first);
  });
});

describe("githubFiles issue forms", () => {
  it("writes a bug form that follows GitHub's form rules", () => {
    const form = FORM_SCHEMA.parse(parseYaml(contentOf(githubFiles(make()).outputs, FORM)));
    for (const item of form.body.filter((entry) => entry.type !== "markdown")) {
      expect(typeof item.id).toBe("string");
      expect(typeof item.attributes.label).toBe("string");
    }
    const ids = form.body.flatMap((item) => (item.id === undefined ? [] : [item.id]));
    expect(new Set(ids).size).toBe(ids.length);
  });

  it("writes a chooser with blank issues off and a link to the advisories", () => {
    const config = CHOOSER_SCHEMA.parse(parseYaml(contentOf(githubFiles(make()).outputs, CHOOSER)));
    expect(config.contact_links.map((link) => link.url)).toStrictEqual([ADVISORIES]);
  });
});

describe("githubFiles refusals", () => {
  it.each(PATHS)("refuses a hand-written %s", (path) => {
    const files = { "package.json": PACKAGE_JSON, [path]: "mine\n" };
    expect(githubFiles(make({ files }))).toStrictEqual({
      errors: [`${path} is hand-written; delete it so repo sync can own it`],
      outputs: [],
    });
  });
});

function pkg(files: Record<string, string>): Setup {
  return { files };
}

describe("githubFiles skips", () => {
  it.each<[string, Setup]>([
    ["a private root", { manifest: { name: "@acme/app", private: true } }],
    ["an unmarked root", { manifest: { name: "@acme/app" } }],
    ["an unnamed root", { manifest: { private: false } }],
    ["the pack off", { packs: ["standards"] }],
    ["no owner", { owner: false }],
    ["no package.json", pkg({})],
    ["unparseable package.json", pkg({ "package.json": "{" })],
    ["a non-object package.json", pkg({ "package.json": "null" })],
    ["no repository", pkg({ "package.json": "{}" })],
    ["a repository off GitHub", pkg({ "package.json": '{"repository":"https://example.com/a/b"}' })],
  ])("writes nothing for %s", (_name, setup) => {
    expect(githubFiles(make(setup))).toStrictEqual({ errors: [], outputs: [] });
  });
});
