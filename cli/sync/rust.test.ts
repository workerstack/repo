import { expect, it } from "vitest";
import { BASE_CONFIG } from "../fixtures/base-config.ts";
import type { Pack } from "../config.ts";
import type { SyncContext } from "./outputs.ts";
import { rust } from "./rust.ts";

/** A context with `packs` whose root holds `files`. */
function context(packs: Pack[], files: Record<string, string>): SyncContext {
  return {
    root: "/work",
    config: { packs, agents: { hosts: [], skills: [] }, ...BASE_CONFIG },
    workspace: { root: "/work", manifest: {}, packages: [] },
    read: (rel) => files[rel] ?? null,
  };
}

const HEADER = "# Generated by repo sync. Do not edit.";
const whole = (path: string, content: string) => ({ kind: "file", path, content, tracked: false, managed: "whole" });

it("writes the toolchain pin, the rustfmt defaults and the clippy limits as untracked whole files", () => {
  expect(rust(context(["standards"], { "Cargo.toml": "[package]\n" }))).toEqual({
    outputs: [
      whole(
        "rust-toolchain.toml",
        `${HEADER}\n[toolchain]\nchannel = "1.99.1"\ncomponents = ["rustfmt", "clippy"]\nprofile = "minimal"\n`,
      ),
      whole("rustfmt.toml", `${HEADER}\n# rustfmt's defaults apply.\n`),
      whole(
        "clippy.toml",
        `${HEADER}\nallow-unwrap-in-tests = true\nallow-expect-in-tests = true\ntoo-many-lines-threshold = 30\ntoo-many-arguments-threshold = 3\n`,
      ),
    ],
    errors: [],
  });
});

it("writes nothing without a root Cargo.toml", () => {
  expect(rust(context(["standards"], { "package.json": "{}" }))).toEqual({ outputs: [], errors: [] });
});

it("writes nothing without the standards pack", () => {
  expect(rust(context(["agents", "docs"], { "Cargo.toml": "" }))).toEqual({ outputs: [], errors: [] });
});

it("accepts a root Cargo.toml that is empty", () => {
  expect(rust(context(["standards"], { "Cargo.toml": "" })).outputs).toHaveLength(3);
});
