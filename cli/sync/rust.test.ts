import { parse } from "smol-toml";
import { expect, it } from "vitest";
import { BASE_CONFIG } from "../fixtures/base-config.ts";
import type { Pack } from "../config.ts";
import type { SyncContext } from "./outputs.ts";
import { rust } from "./rust.ts";

/** A context with `packs` whose root holds `files`. */
function context(packs: Pack[], files: Record<string, string>): SyncContext {
  return {
    root: "/work",
    config: { packs, agents: { hosts: [], skills: [] }, ...BASE_CONFIG },
    workspace: { root: "/work", manifest: {}, packages: [] },
    read: (rel) => files[rel] ?? null,
  };
}

const HEADER = "# Generated by repo sync. Do not edit.";
const DENY = `${HEADER}
[graph]
all-features = true

[advisories]
unmaintained = "all"
unsound = "all"
yanked = "deny"

[licenses]
confidence-threshold = 0.93
allow = [
  "0BSD",
  "Apache-2.0",
  "Apache-2.0 WITH LLVM-exception",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "BSL-1.0",
  "CC0-1.0",
  "ISC",
  "MIT",
  "MIT-0",
  "Unicode-3.0",
  "Unlicense",
  "Zlib",
]
unused-allowed-license = "allow"

[licenses.private]
ignore = true

[bans]
multiple-versions = "warn"
wildcards = "deny"
allow-wildcard-paths = true

[sources]
unknown-registry = "deny"
unknown-git = "deny"
`;
const whole = (path: string, content: string) => ({ kind: "file", path, content, tracked: false, managed: "whole" });

it("writes the toolchain pin, the rustfmt defaults and the clippy limits as untracked whole files", () => {
  expect(rust(context(["standards"], { "Cargo.toml": "[package]\n" }))).toEqual({
    outputs: [
      whole(
        "rust-toolchain.toml",
        `${HEADER}\n[toolchain]\nchannel = "1.99.1"\ncomponents = ["rustfmt", "clippy"]\nprofile = "minimal"\n`,
      ),
      whole("rustfmt.toml", `${HEADER}\n# rustfmt's defaults apply.\n`),
      whole(
        "clippy.toml",
        `${HEADER}\nallow-unwrap-in-tests = true\nallow-expect-in-tests = true\ntoo-many-lines-threshold = 30\ntoo-many-arguments-threshold = 3\n`,
      ),
      whole("deny.toml", DENY),
    ],
    errors: [],
  });
});

it("writes a deny.toml that parses to the supply-chain policy", () => {
  const out = rust(context(["standards"], { "Cargo.toml": "" })).outputs.find((o) => o.path === "deny.toml");
  const parsed = parse(out?.kind === "file" ? out.content : "") /* smol-toml returns plain tables */ as Record<
    string,
    Record<string, unknown>
  >;
  expect(Object.keys(parsed)).toEqual(["graph", "advisories", "licenses", "bans", "sources"]);
  expect(parsed.advisories).toEqual({ unmaintained: "all", unsound: "all", yanked: "deny" });
  expect(parsed.licenses?.allow).toContain("Apache-2.0 WITH LLVM-exception");
  expect(parsed.licenses?.private).toEqual({ ignore: true });
  expect(parsed.bans).toEqual({ "multiple-versions": "warn", wildcards: "deny", "allow-wildcard-paths": true });
  expect(parsed.sources).toEqual({ "unknown-registry": "deny", "unknown-git": "deny" });
});

it("writes nothing without a root Cargo.toml", () => {
  expect(rust(context(["standards"], { "package.json": "{}" }))).toEqual({ outputs: [], errors: [] });
});

it("writes nothing without the standards pack", () => {
  expect(rust(context(["agents", "docs"], { "Cargo.toml": "" }))).toEqual({ outputs: [], errors: [] });
});

it("accepts a root Cargo.toml that is empty", () => {
  expect(rust(context(["standards"], { "Cargo.toml": "" })).outputs).toHaveLength(4);
});
