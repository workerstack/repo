import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { expect, it, vi } from "vitest";

import { fixtureDirs } from "../dev/capture-tree-goldens.ts";
import { CONFIG_FILE } from "./config.constants.ts";
import { manifestPaths, read, syncWith, tempDir, useSyncKit, write } from "./fixtures/sync-kit.ts";
import { POST_PASSES } from "./sync-outputs.ts";
import { hasOwnedHeader } from "./sync/header.ts";
import { formatOf } from "./sync/validate.ts";

useSyncKit();
vi.setConfig({ testTimeout: 120_000 });
const EVERY_PACK =
  'export default { packs: ["agents", "standards", "docs", "release", "workspace"], agents: { hosts: ["claude", "codex", "antigravity", "grok", "cursor"] }, owner: { name: "A", github: "a" } };\n';
/** Any header line sync ever wrote, new or legacy, wherever it sits in a file. */
const ANY_HEADER = /@generated by @workerstack\/repo|Generated by (?:repo sync|emit-mcp-policy\.ts|lessons\.ts)/;

/** The consumer fixture as a public workspace with a package, a Rust crate and a lessons dir, on this repo's stock. */
function everyPack(files: Record<string, string> = {}): string {
  const root = tempDir();
  fs.cpSync(fixtureDirs().consumer, root, { recursive: true });
  write(root, CONFIG_FILE, EVERY_PACK);
  const manifest = { name: "golden-consumer", private: false, type: "module", workspaces: ["packages/*"] };
  write(root, "package.json", JSON.stringify({ ...manifest, repository: { url: "git+https://github.com/a/b.git" } }));
  write(root, "packages/api/package.json", JSON.stringify({ name: "@acme/api" }));
  write(root, "packages/api/references/INDEX.md", "# Api\n");
  write(root, "Cargo.toml", '[package]\nname = "x"\n');
  fs.mkdirSync(path.join(root, ".repo", "lessons"), { recursive: true });
  const scope = path.join(root, "node" + "_modules", "@workerstack");
  fs.mkdirSync(scope, { recursive: true });
  const self = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  fs.symlinkSync(self, path.join(scope, "repo"), "dir");
  for (const [rel, text] of Object.entries(files)) write(root, rel, text);
  return root;
}
/** A real sync with every generator and pass. */
const syncAll = (cwd: string, ...args: string[]) => syncWith(cwd, { post: POST_PASSES }, ...args);
/** Every regular file sync recorded in its manifest, with its text. */
const written = (root: string): [string, string][] =>
  manifestPaths(root)
    .filter((rel) => fs.lstatSync(path.join(root, rel)).isFile())
    .map((rel) => [rel, read(root, rel)]);
const headerCount = (text: string) => text.split("\n").filter((line) => ANY_HEADER.test(line)).length;
/** The first `lines` lines of the file at `rel`. */
const head = (root: string, rel: string, lines = 1) => read(root, rel).split("\n").slice(0, lines).join("\n");

const LEGACY_OUTPUTS = {
  ".githooks/pre-commit": "#!/bin/sh\n# Generated by repo sync. Do not edit.\nold\n",
  ".github/workflows/ci.yml": "# Generated by repo sync. Do not edit.\nname: old\n",
  "README.md": "<!-- Generated by repo sync from references/INDEX.md. Do not edit. -->\n# Old\n",
  "bunfig.toml": "# Generated by repo sync. Do not edit.\n[install]\n",
  "vitest.config.ts": "// Generated by repo sync. Do not edit.\nexport default {};\n",
};

it("writes the one header line in each format's syntax, on line 2 after a shebang", async () => {
  const root = everyPack();
  const { code } = await syncAll(root);
  expect(code).toBe(0);
  const hash = "# @generated by @workerstack/repo";
  for (const rel of [".github/workflows/ci.yml", "bunfig.toml", ".codex/config.toml", ".grok/config.toml"])
    expect(head(root, rel), rel).toBe(hash);
  expect(head(root, ".github/CODEOWNERS")).toBe(hash);
  expect(head(root, ".githooks/pre-commit", 2)).toBe(`#!/bin/sh\n${hash}`);
  for (const rel of [".vscode/tasks.json", ".oxfmtrc.jsonc", "vitest.config.ts"])
    expect(head(root, rel), rel).toBe("// @generated by @workerstack/repo");
  const markdown = ["README.md", ".github/PULL_REQUEST_TEMPLATE.md"];
  for (const rel of [...markdown, ".repo/lessons/INDEX.md"])
    expect(head(root, rel), rel).toBe("<!-- @generated by @workerstack/repo -->");
});

it("puts exactly one header on every whole file whose format takes a comment, and none on strict JSON or frontmatter", async () => {
  const root = everyPack();
  const { code } = await syncAll(root);
  expect(code).toBe(0);
  const files = written(root);
  expect(files.length).toBeGreaterThan(50);
  for (const [rel, text] of files) {
    const takes = formatOf(rel)?.comment != null && !text.startsWith("---\n") && !rel.endsWith("AGENTS.md");
    expect(headerCount(text), rel).toBe(takes ? 1 : 0);
    expect(!takes || hasOwnedHeader(text), rel).toBe(true);
  }
  for (const rel of [".claude/settings.json", ".agents/mcp_config.json", ".oxlintrc.json", "knip.json", "turbo.json"])
    expect(headerCount(read(root, rel)), rel).toBe(0);
  for (const rel of [".claude/agents/scout.md", ".claude/rules/testing.md", ".agents/rules/testing.md"])
    expect(read(root, rel).startsWith("---\n"), rel).toBe(true);
  expect(await syncAll(root, "--check")).toEqual({ code: 0, stderr: "", stdout: "repo sync: up to date\n" });
});

it("rewrites ci.yml, bunfig.toml, a git hook, README.md and vitest.config.ts that carry a legacy header", async () => {
  const root = everyPack(LEGACY_OUTPUTS);
  const result = await syncAll(root);
  expect(result.stderr).toBe("");
  expect(result.code).toBe(0);
  for (const rel of Object.keys(LEGACY_OUTPUTS)) {
    const text = read(root, rel);
    expect(headerCount(text), rel).toBe(1);
    expect(text, rel).toContain("@generated by @workerstack/repo");
    expect(text, rel).not.toContain("Generated by repo sync");
  }
});
