  "<!-- /repo:stack -->\n";
const OUTPUTS = ["bunfig.toml", ".gitignore", "references/INDEX.md"];
const OLD = new Date("2020-01-01T00:00:00Z");

const temps: string[] = [];

afterEach(() => {
  vi.restoreAllMocks();
  for (const dir of temps.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

function tempDir(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "workerstack-sync-"));
  temps.push(dir);
  return dir;
}

function write(root: string, rel: string, text: string): void {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

function read(root: string, rel: string): string {
  return fs.readFileSync(path.join(root, rel), "utf8");
}

/** Every file under `root`, root-relative, with its bytes. */
function snapshot(root: string): Record<string, string> {
  const files: Record<string, string> = {};
  for (const rel of fs.readdirSync(root, { recursive: true, encoding: "utf8" }).sort()) {
    const file = path.join(root, rel);
    if (fs.statSync(file).isFile()) files[rel.replaceAll("\\", "/")] = fs.readFileSync(file, "latin1");
  }
  return files;
}

/** A temp workspace repo with the docs pack, one package and a `@workerstack/repo` dependency. */
function fixture(config = 'export default { packs: ["agents", "docs"], agents: { hosts: ["claude"] } }\n'): string {
  const root = tempDir();
  write(root, CONFIG_FILE, config);
  write(
    root,
    "package.json",
    JSON.stringify({ name: "fixture", workspaces: ["packages/*"], devDependencies: { "@workerstack/repo": "^1.0.0" } }),
  );
  write(root, "packages/api/package.json", JSON.stringify({ name: "@acme/api" }));
  write(root, "packages/api/references/INDEX.md", "# API worker\n");
  return root;
}

/** Runs `repo sync` in `cwd`, capturing what it prints. */
async function sync(cwd: string, ...args: string[]) {
  return syncWith(cwd, { generators: [bunfig, gitignore, index] }, ...args);
}

async function syncWith(cwd: string, deps: SyncDeps, ...args: string[]) {
  const out: string[] = [];
  const err: string[] = [];
  const code = await runSync(args, { cwd, stdout: (s) => out.push(s), stderr: (s) => err.push(s) }, deps);
  return { code, stdout: out.join(""), stderr: err.join("") };
}

function mtimes(root: string): number[] {
  return OUTPUTS.map((rel) => fs.statSync(path.join(root, rel)).mtimeMs);
}

function age(root: string): void {
  for (const rel of OUTPUTS) fs.utimesSync(path.join(root, rel), OLD, OLD);
}

describe("runSync", () => {
  it("writes every output under the root on the first run, then reports up to date without touching them", async () => {
    const root = fixture();

    expect(await sync(root)).toEqual({
      code: 0,
      stdout: "repo sync: wrote bunfig.toml, .gitignore, references/INDEX.md\n",
      stderr: "",
    });
    expect(read(root, "bunfig.toml")).toBe(BUNFIG);
    expect(read(root, ".gitignore")).toBe(GITIGNORE);
    expect(read(root, "references/INDEX.md")).toBe(INDEX);

    age(root);
    const before = mtimes(root);
    expect(await sync(root)).toEqual({ code: 0, stdout: "repo sync: up to date\n", stderr: "" });
    expect(mtimes(root)).toEqual(before);
  });

  it("refuses a config without the agents pack in this repo, whose trees are the stock source, and touches nothing", async () => {
    const root = fixture('export default { packs: ["docs"] }\n');
    write(root, "package.json", JSON.stringify({ name: "@workerstack/repo" }));
    write(root, ".claude/skills/ask/SKILL.md", "stock\n");
    expect(await sync(root)).toEqual({
      code: 1,
      stdout: "",
      stderr: 'repo sync: workerstack.config.ts: this repo ships the agent trees as its stock source; keep "agents" in packs\n',
    });
    expect(read(root, ".claude/skills/ask/SKILL.md")).toBe("stock\n");
    expect(fs.existsSync(path.join(root, "bunfig.toml"))).toBe(false);
  });

  it("finds the root from a nested cwd and writes there", async () => {
    const root = fixture();
    expect((await sync(path.join(root, "packages", "api"))).code).toBe(0);
    expect(read(root, "bunfig.toml")).toBe(BUNFIG);
    expect(fs.existsSync(path.join(root, "packages", "api", "bunfig.toml"))).toBe(false);
  });

  it("rewrites only the files that drifted and leaves no temp files", async () => {
    const root = fixture();
    await sync(root);
    write(root, "bunfig.toml", `${BUNFIG}x\n`);
    age(root);
    const [, gitignore, index] = mtimes(root);

    expect(await sync(root)).toEqual({ code: 0, stdout: "repo sync: wrote bunfig.toml\n", stderr: "" });
    expect(read(root, "bunfig.toml")).toBe(BUNFIG);
    expect(mtimes(root).slice(1)).toEqual([gitignore, index]);
    expect(fs.readdirSync(root).filter((name) => name.includes(".tmp"))).toEqual([]);
  });

  it("keeps the hand-written text around the managed parts", async () => {
    const root = fixture();
    write(root, ".gitignore", "node_modules/\n.tmp/\n");
    write(root, "references/INDEX.md", "# Docs\n\nHand-written.\n");
    await sync(root);
    expect(read(root, ".gitignore")).toBe(`node_modules/\n.tmp/\n\n${GITIGNORE}`);
    expect(read(root, "references/INDEX.md")).toBe(`# Docs\n\nHand-written.\n${INDEX.slice("# References\n".length)}`);
  });

  it("treats a file whose bytes differ only in line endings as drifted", async () => {
    const root = fixture();
    await sync(root);
    write(root, "bunfig.toml", BUNFIG.replaceAll("\n", "\r\n"));
    expect(await sync(root, "--check")).toEqual({
      code: 1,
      stdout: "",
      stderr: "repo sync: bunfig.toml is out of date; run `bun repo sync`\n",
    });
  });

  it("--check reports up to date and exits 0 when nothing drifted", async () => {
    const root = fixture();
    await sync(root);
    expect(await sync(root, "--check")).toEqual({ code: 0, stdout: "repo sync: up to date\n", stderr: "" });
  });

  it("--check names every stale file, exits 1 and writes nothing", async () => {
    const root = fixture();
    write(root, "bunfig.toml", `${BUNFIG}x\n`);
    const before = snapshot(root);

    expect(await sync(root, "--check")).toEqual({
      code: 1,
      stdout: "",
      stderr:
        "repo sync: bunfig.toml is out of date; run `bun repo sync`\n" +
        "repo sync: .gitignore is out of date; run `bun repo sync`\n" +
        "repo sync: references/INDEX.md is out of date; run `bun repo sync`\n",
    });
    expect(snapshot(root)).toEqual(before);
  });

  it("a config error exits 1 and leaves every file byte-identical", async () => {
    const root = fixture("export default { pakcs: [] }\n");
    write(root, "bunfig.toml", `${BUNFIG}x\n`);
    write(root, ".gitignore", "node_modules/\n");
    const before = snapshot(root);

    expect(await sync(root)).toEqual({
      code: 1,
      stdout: "",
      stderr: 'repo sync: workerstack.config.ts: unknown key "pakcs"\n',
    });
    expect(snapshot(root)).toEqual(before);
  });

  it("a generator error exits 1 and writes none of the valid outputs", async () => {
    const root = fixture();
    write(root, "bunfig.toml", `${BUNFIG}x\n`);
    write(root, "references/INDEX.md", "# References\n\n<!-- repo:stack -->\n");
    const before = snapshot(root);

    expect(await sync(root)).toEqual({
      code: 1,
      stdout: "",
      stderr: 'repo sync: references/INDEX.md: "<!-- repo:stack -->" has no closing "<!-- /repo:stack -->"\n',
    });
    expect(snapshot(root)).toEqual(before);
  });

  it("a workspace error exits 1 and writes nothing", async () => {
    const root = fixture();
    write(root, "packages/api/package.json", "{");
    const before = snapshot(root);

    const result = await sync(root);
    expect(result.code).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toMatch(/^repo sync: packages\/api\/package\.json: not valid JSON: .+\n$/);
    expect(snapshot(root)).toEqual(before);
  });

  it("reports a file it cannot read instead of treating it as missing", async () => {
    const root = fixture();
    write(root, "references/INDEX.md/stray.txt", "a directory where the index belongs\n");
    const before = snapshot(root);

    const result = await sync(root);
    expect(result.code).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toMatch(/^repo sync: references\/INDEX\.md: cannot read: EISDIR\b.*\n$/);
    expect(snapshot(root)).toEqual(before);
  });

  it("reports a failed write, removes its temp file and exits 1", async () => {
    const root = fixture();
    const rename = vi.spyOn(fs, "renameSync").mockImplementationOnce(() => {
      throw Object.assign(new Error("EACCES: permission denied, rename"), { code: "EACCES" });
    });

    expect(await sync(root)).toEqual({
      code: 1,
      stdout: "",
      stderr: "repo sync: bunfig.toml: cannot write: EACCES: permission denied, rename; restored 0 outputs, nothing changed\n",
    });
    expect(rename).toHaveBeenCalledOnce();
    expect(fs.readdirSync(root).sort()).toEqual([CONFIG_FILE, "package.json", "packages"].sort());
  });

  it("--postinstall prints an error and exits 0", async () => {
    const root = fixture("export default { pakcs: [] }\n");
    expect(await sync(root, "--postinstall")).toEqual({
      code: 0,
      stdout: "",
      stderr: 'repo sync: workerstack.config.ts: unknown key "pakcs"\n',
    });
    expect(fs.existsSync(path.join(root, "bunfig.toml"))).toBe(false);
  });

  it("--postinstall writes like a plain run when there is no error", async () => {
    const root = fixture();
    expect(await sync(root, "--postinstall")).toEqual({
      code: 0,
      stdout: "repo sync: wrote bunfig.toml, .gitignore, references/INDEX.md\n",
      stderr: "",
    });
  });

  it("says to run repo init when no config exists in cwd or any parent", async () => {
    const cwd = tempDir();
    expect(await sync(cwd)).toEqual({
      code: 1,
      stdout: "",
      stderr: `repo sync: no workerstack.config.ts in ${cwd} or any parent; run \`bun repo init\`\n`,
    });
    expect(fs.readdirSync(cwd)).toEqual([]);
    expect((await sync(cwd, "--postinstall")).code).toBe(0);
  });

  it("produces identical bytes across runs and roots", async () => {
    const first = fixture();
    const second = fixture();
    await sync(first);
    const once = snapshot(first);
    await sync(first);
    await sync(second);
    expect(snapshot(first)).toEqual(once);
    expect(snapshot(second)).toEqual(once);
  });

  it.each([
    [["--force"], "repo sync: unknown flag --force; use --check or --postinstall\n"],
    [["extra"], "repo sync: unknown flag extra; use --check or --postinstall\n"],
    [["--check", "--postinstall"], "repo sync: use --check or --postinstall, not both\n"],
  ])("%j is a usage error that exits 1 and writes nothing", async (args, stderr) => {
    const root = fixture();
    const before = snapshot(root);
    expect(await sync(root, ...args)).toEqual({ code: 1, stdout: "", stderr });
    expect(snapshot(root)).toEqual(before);
  });
});

describe("planSync", () => {
  it("runs every generator in order and concatenates outputs and errors", () => {
    const files: Record<string, string> = {
      "bunfig.toml": "[test]\n",
      ".gitignore": "# >>> @workerstack/repo\n",
    };
    expect(
      planSync({
        root: "/repo",
        config: { packs: ["docs"], agents: NO_AGENTS },
        workspace: { root: "/repo", manifest: {}, packages: [] },
        read: (rel) => files[rel] ?? null,
      }),
    ).toEqual({
      outputs: [
        {
          kind: "file",
          path: "references/INDEX.md",
          content: "# References\n\n<!-- repo:stack -->\n<!-- /repo:stack -->\n",
          tracked: true,
        },
      ],
      errors: [
        "bunfig.toml is hand-written; delete it so repo sync can own it",
        '.gitignore: "# >>> @workerstack/repo" has no closing "# <<< @workerstack/repo"',
      ],
    });
  });

  it("reports a generator that throws as an error and keeps running the others", () => {
    const boom: Generator = () => {
      throw new Error("EACCES: cannot read x");
    };
    const ok: Generator = () => ({ outputs: [file("a.txt")], errors: [] });
    const plan = planSync(
      {
        root: "/repo",
        config: { packs: ["docs"], agents: NO_AGENTS },
        workspace: { root: "/repo", manifest: {}, packages: [] },
        read: () => null,
      },
      [boom, ok],
    );
    expect(plan).toEqual({ outputs: [file("a.txt")], errors: ["EACCES: cannot read x"] });
  });

  it("plans all three outputs for a clean repo", () => {
    const plan = planSync({
      root: "/repo",
      config: { packs: ["docs"], agents: NO_AGENTS },
      workspace: { root: "/repo", manifest: {}, packages: [] },
      read: () => null,
    });
    expect(plan.errors).toEqual([]);
    expect(plan.outputs.map((output) => output.path)).toEqual(OUTPUTS);
  });
});

const file = (path: string, content = `${path}\n`): Output => ({ kind: "file", path, content, tracked: false });
const link = (path: string, target: string): Output => ({ kind: "link", path, target, tracked: false });
/** A generator that returns exactly `outputs`, replacing the real ones. */
const generating = (...outputs: Output[]): Generator[] => [() => ({ outputs, errors: [] })];
/** The same, with every path accepted as text, so these tests need not name registered formats. */
const only = (...outputs: Output[]): { generators: Generator[]; formats: FormatEntry[] } => ({
  generators: generating(...outputs),
  formats: [{ match: () => true, format: "text" }],
});
const manifestPaths = (root: string): string[] => (JSON.parse(read(root, MANIFEST_REL)) as { paths: string[] }).paths;
const exists = (root: string, rel: string): boolean => {
  try {
    fs.lstatSync(path.join(root, rel));
    return true;
  } catch {
    return false;
  }
};

describe("runSync link outputs", () => {
  it("creates a link, keeps it while current and replaces it when it points elsewhere", async () => {
    const root = fixture();
    fs.mkdirSync(path.join(root, "store/a"), { recursive: true });
    fs.mkdirSync(path.join(root, "store/b"), { recursive: true });
    const symlink = vi.spyOn(fs, "symlinkSync");

    const deps = only(link("tree/skill", "../store/a"));
    expect(await syncWith(root, deps)).toEqual({ code: 0, stdout: "repo sync: wrote tree/skill\n", stderr: "" });
    expect(linkText(path.join(root, "tree/skill"))).toBe("../store/a");
    expect(symlink).toHaveBeenCalledTimes(1);

    expect(await syncWith(root, deps)).toEqual({ code: 0, stdout: "repo sync: up to date\n", stderr: "" });
    expect(symlink).toHaveBeenCalledTimes(1);

    expect((await syncWith(root, only(link("tree/skill", "../store/b")))).code).toBe(0);
    expect(linkText(path.join(root, "tree/skill"))).toBe("../store/b");
    expect(symlink).toHaveBeenCalledTimes(2);
  });

  it("keeps a link whose text is exactly the planned target", async () => {
    const root = fixture();
    fs.mkdirSync(path.join(root, "store"));
    fs.mkdirSync(path.join(root, "tree"));
    // A junction needs no privilege on win32 and is a plain symlink elsewhere, so the posix check runs on every OS.
    fs.symlinkSync(path.join(root, "store"), path.join(root, "tree/skill"), "junction");
    const text = fs.readlinkSync(path.join(root, "tree/skill"));
    await syncWith(root, { ...only(link("tree/skill", text)), platform: "linux" });
    const symlink = vi.spyOn(fs, "symlinkSync");
    expect(await syncWith(root, { ...only(link("tree/skill", text)), platform: "linux" })).toEqual({
      code: 0,
      stdout: "repo sync: up to date\n",
      stderr: "",
    });
    expect(symlink).not.toHaveBeenCalled();
  });

  it("replaces a real file that stands where a link belongs", async () => {
    const root = fixture();
    fs.mkdirSync(path.join(root, "store"));
    write(root, "tree/skill", "old\n");
    expect((await syncWith(root, only(link("tree/skill", "../store")))).code).toBe(0);
    expect(fs.lstatSync(path.join(root, "tree/skill")).isSymbolicLink()).toBe(true);
  });

  it("makes a junction with an absolute target on win32", async () => {
    const root = fixture();
    fs.mkdirSync(path.join(root, "store"));
    const symlink = vi.spyOn(fs, "symlinkSync");
    await syncWith(root, { ...only(link("tree/skill", "../store")), platform: "win32" });
    expect(symlink).toHaveBeenCalledWith(path.join(root, "store"), path.join(root, "tree/skill"), "junction");
  });

  // A win32 junction holds an absolute target, so there a link is matched by the path it names (the next test).
  it.skipIf(process.platform === "win32")("rewrites a link whose text differs, even when it resolves to the same directory", async () => {
    const root = fixture();
    const store = path.join(root, "store");
    fs.mkdirSync(store);
    const alias = aliasOf(store);
    try {
      expect((await syncWith(root, only(link("tree/skill", alias)))).code).toBe(0);
      expect(await syncWith(root, only(link("tree/skill", store)))).toEqual({
        code: 0,
        stdout: "repo sync: wrote tree/skill\n",
        stderr: "",
      });
      expect(fs.readlinkSync(path.join(root, "tree/skill"))).toBe(store);
    } finally {
      removeAlias(alias);
    }
  });

  it("on win32 treats a target whose parent dirs are spelled another way as the same directory", async () => {
    const root = fixture();
    const store = path.join(root, "store");
    fs.mkdirSync(store);
    const alias = aliasOf(root);
    try {
      expect((await syncWith(root, { ...only(link("tree/skill", path.join(alias, "store"))), platform: "win32" })).code).toBe(0);
      const symlink = vi.spyOn(fs, "symlinkSync");
      expect(await syncWith(root, { ...only(link("tree/skill", store)), platform: "win32" })).toEqual({
        code: 0,
        stdout: "repo sync: up to date\n",
        stderr: "",
      });
      expect(symlink).not.toHaveBeenCalled();
    } finally {
      removeAlias(alias);
    }
  });

  // A posix symlink on win32 needs a privilege the junction does not, so win32 runs only its own platform.
  const platforms = process.platform === "win32" ? (["win32"] as const) : (["linux", "win32"] as const);
  it.each(platforms)(
    "on %s rewrites a link that reaches the target only through another generated link, so pruning that link leaves none dangling",
    async (platform) => {
      const root = fixture();
      fs.mkdirSync(path.join(root, "store/x"), { recursive: true });
      const through = [link(".agents/skills/x", "../../store/x"), link(".claude/skills/x", "../../.agents/skills/x")];
      expect((await syncWith(root, { generators: [() => ({ outputs: through, errors: [] })], platform })).code).toBe(0);

      const direct = await syncWith(root, { ...only(link(".claude/skills/x", "../../store/x")), platform });
      expect(direct.code).toBe(0);
      expect(direct.stdout).toBe("repo sync: wrote .claude/skills/x; removed .agents/skills/x\n");
      expect(linkText(path.join(root, ".claude/skills/x"))).toBe("../../store/x");
      expect(fs.existsSync(path.join(root, ".claude/skills/x"))).toBe(true);
      expect(exists(root, ".agents")).toBe(false);
    },
  );

  it("reports a failed link and exits 1", async () => {
    const root = fixture();
    fs.mkdirSync(path.join(root, "store"));
    vi.spyOn(fs, "symlinkSync").mockImplementationOnce(() => {
      throw new Error("EPERM: operation not permitted, symlink");
    });
    // Injected, so the posix link call runs on win32 too; the mock keeps it from needing the symlink privilege.
    expect(await syncWith(root, { ...only(link("tree/skill", "../store")), platform: "linux" })).toEqual({
      code: 1,
      stdout: "",
      stderr: "repo sync: tree/skill: cannot write: EPERM: operation not permitted, symlink; restored 0 outputs, nothing changed\n",
    });
  });
});

