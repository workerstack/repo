/** The Cargo.lock that `cargo generate-lockfile` writes, offline, for a crate named `name` with no dependencies. */
export function cargoLock(name: string): string {
  return `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "${name}"\nversion = "0.1.0"\n`;
}
