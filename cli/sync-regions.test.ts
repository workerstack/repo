import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { afterEach, describe, expect, it } from "vitest";

import { CONFIG_FILE } from "./config.constants.ts";
import { runSync, type SyncDeps } from "./sync.ts";
import { gitFiles } from "./sync/git-files.ts";
import { MANIFEST_REL, readManifest, renderManifest } from "./sync/manifest.ts";
import { bunfig } from "./sync/outputs.ts";

const WEB = "packages/web/references/INDEX.md";
const OLD_IGNORE = "tools/.gitignore";
const ONLY_REGION = "docs/references/INDEX.md";
const OWNED = "old.yml";
const USER_SHAPED = "notes/.gitignore";
const SETTINGS = ".vscode/settings.json";
const FILES: Record<string, string> = {
  [WEB]:
    "# Web\n\nMy notes.\n\n<!-- repo:deps 1a2b3c4d -->\n- [@acme/api](../../api/references/INDEX.md)\n<!-- /repo:deps -->\n",
  [OLD_IGNORE]: "dist/\n# >>> @workerstack/repo (generated by repo sync)\n.tmp/\n# <<< @workerstack/repo\n",
  [ONLY_REGION]: "\n<!-- repo:deps 0a1b2c3d -->\n- a\n<!-- /repo:deps -->\n  \n",
  [USER_SHAPED]: "# repo: vendored\nvendor/\n# /repo:vendored\n",
  [OWNED]: "# @generated by @workerstack/repo\na: 1\n",
  [SETTINGS]: "{,\n",
};
const DEPS: SyncDeps = { generators: [bunfig], post: [gitFiles] };
const WARNING = `repo sync: ${SETTINGS}: not valid JSONC at line 1 (ValueExpected); left as is\n`;

const temps: string[] = [];
afterEach(() => {
  for (const dir of temps.splice(0)) fs.rmSync(dir, { force: true, recursive: true });
});

/** A synced consumer, outside git, whose manifest still names the fixture files no output writes any more. */
async function consumer(named = [WEB, OLD_IGNORE, ONLY_REGION, OWNED]): Promise<string> {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "workerstack-sync-regions-")));
  temps.push(root);
  const write = (rel: string, text: string) => {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), text);
  };
  write(CONFIG_FILE, 'export default { packs: ["docs"] }\n');
  write("package.json", JSON.stringify({ name: "app" }));
  for (const [rel, text] of Object.entries(FILES)) write(rel, text);
  const { code } = await sync(root);
  expect(code).toBe(0);
  write(MANIFEST_REL, renderManifest([...readManifest(root).paths, ...named]));
  return root;
}

async function sync(cwd: string, args: string[] = [], deps: SyncDeps = DEPS) {
  const out: string[] = [];
  const err: string[] = [];
  const code = await runSync(args, { cwd, stderr: (s) => err.push(s), stdout: (s) => out.push(s) }, deps);
  return { code, stderr: err.join(""), stdout: out.join("") };
}

const read = (root: string, rel: string) => fs.readFileSync(path.join(root, rel), "utf8");
const exists = (root: string, rel: string) => fs.existsSync(path.join(root, rel));

describe("runSync over a shared path no output writes", () => {
  it("--check names each file with regions and each owned path, writes nothing and exits 1", async () => {
    const root = await consumer();
    const drift = (rel: string) => `repo sync: ${rel} has regions no output writes; run \`bun repo sync\`\n`;
    const stale = `repo sync: ${OWNED} is stale and would be removed; run \`bun repo sync\`\n`;
    expect(await sync(root, ["--check"])).toEqual({
      code: 1,
      stderr: [WARNING, stale, ...[ONLY_REGION, WEB, OLD_IGNORE].sort().map(drift)].join(""),
      stdout: "",
    });
    for (const [rel, text] of Object.entries(FILES)) expect(read(root, rel)).toBe(text);
  });
});

describe("runSync cutting a shared path no output writes", () => {
  it("prints a line per region cut and per file left blank, and names the cut files in the summary", async () => {
    const root = await consumer();
    expect(await sync(root)).toEqual({
      code: 0,
      stderr: [
        WARNING,
        `repo sync: cut repo:deps from ${ONLY_REGION}\n`,
        `repo sync: removed ${ONLY_REGION}: nothing but its regions was in it\n`,
        `repo sync: cut repo:deps from ${WEB}\n`,
        `repo sync: cut the old markers from ${OLD_IGNORE}\n`,
      ].join(""),
      stdout: `repo sync: removed ${OWNED}; cut ${[ONLY_REGION, WEB, OLD_IGNORE].sort().join(", ")}\n`,
    });
  });

  it("keeps the user's lines, a legacy pair cut too, removes the blank file and the owned path, then is up to date", async () => {
    const root = await consumer();
    await sync(root);
    expect(read(root, WEB)).toBe("# Web\n\nMy notes.\n");
    expect(read(root, OLD_IGNORE)).toBe("dist/\n");
    expect(exists(root, ONLY_REGION) || exists(root, OWNED)).toBe(false);
    expect(await sync(root, ["--check"])).toEqual({ code: 0, stderr: WARNING, stdout: "repo sync: up to date\n" });
  });

  it("never touches a marker-less file an output still names, invalid settings JSONC kept as is", async () => {
    const root = await consumer();
    await sync(root);
    expect(read(root, SETTINGS)).toBe(FILES[SETTINGS]);
    expect(readManifest(root).paths).toContain(SETTINGS);
  });
});

describe("runSync when a cut cannot be written", () => {
  it("exits 1 with the error, writes nothing else, and the manifest still names the file", async () => {
    const root = await consumer([WEB]);
    fs.rmSync(path.join(root, "bunfig.toml"), { force: true });
    const refuse: SyncDeps["writeOutput"] = (_root, output) => (output.path === WEB ? "disk full" : null);
    expect(await sync(root, [], { ...DEPS, writeOutput: refuse })).toEqual({
      code: 1,
      stderr: `${WARNING}repo sync: ${WEB}: could not cut: disk full\n`,
      stdout: "",
    });
    expect(read(root, WEB)).toBe(FILES[WEB]);
    expect(exists(root, "bunfig.toml")).toBe(false);
    expect(readManifest(root).paths).toContain(WEB);
  });
});

describe("runSync over a shared path holding only marker-shaped lines sync did not write", () => {
  it("leaves it byte for byte, reports nothing and drops it from the manifest", async () => {
    const root = await consumer([USER_SHAPED]);
    expect(await sync(root)).toEqual({ code: 0, stderr: WARNING, stdout: "repo sync: up to date\n" });
    expect(read(root, USER_SHAPED)).toBe(FILES[USER_SHAPED]);
    expect(readManifest(root).paths).not.toContain(USER_SHAPED);
  });
});
