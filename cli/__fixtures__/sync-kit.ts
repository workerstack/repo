// Shared setup for the `runSync` suites: temp repos, a sync that captures what it prints, and output builders.
import fs from "node:fs";
import path from "node:path";
import { afterEach, expect, vi } from "vitest";
import { CONFIG_FILE } from "../config.constants.ts";
import { runSync, type SyncDeps } from "../sync.ts";
import { tempDir as tempDirNamed, useTempDirs } from "../sync/__fixtures__/temp-dirs.ts";
import { gitFiles, type PostPass } from "../sync/git-files.ts";
import { MANIFEST_REL } from "../sync/manifest.ts";
import { bunfig, index, type Generator, type Output } from "../sync/outputs.ts";
import { regionHash } from "../sync/region.ts";
import type { FormatEntry } from "../sync/validate-formats.ts";

export const BUNFIG: string = '# @generated by @workerstack/repo\n[install]\nlinker = "hoisted"\nauto = "disable"\n';
/** What `fixture`'s repo plans with the bunfig and index generators and the git files pass, in order. */
export const OUTPUTS: readonly string[] = [
  "bunfig.toml",
  "references/INDEX.md",
  "packages/api/references/INDEX.md",
  ".gitignore",
  ".gitattributes",
  ".vscode/settings.json",
];

/** What a sync run returned and printed. */
export type Synced = { code: number; stdout: string; stderr: string };

const extra: string[] = [];

/** Removes every temp dir, and each path `removeAfter` named, and restores every spy after each test of the file. */
export function useSyncKit(): void {
  useTempDirs();
  afterEach(() => {
    for (const made of extra.splice(0)) fs.rmSync(made, { recursive: true, force: true });
    vi.restoreAllMocks();
  });
}

/** Removes `made`, a path a test wrote outside its temp dir, after the test. */
export function removeAfter(made: string): void {
  extra.push(made);
}

/** A new empty temp dir, removed after the test. */
export function tempDir(): string {
  return tempDirNamed("workerstack-sync-");
}

/** Writes `text` at `rel`, first making a file sync left read-only writable, as a hand edit has to. */
export function write(root: string, rel: string, text: string): void {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.lstatSync(file, { throwIfNoEntry: false })?.isFile() === true) fs.chmodSync(file, 0o644);
  fs.writeFileSync(file, text);
}

export function read(root: string, rel: string): string {
  return fs.readFileSync(path.join(root, rel), "utf8");
}

/** Every file under `root`, root-relative, with its bytes. */
export function snapshot(root: string): Record<string, string> {
  const files: Record<string, string> = {};
  for (const rel of fs.readdirSync(root, { recursive: true, encoding: "utf8" }).toSorted()) {
    const file = path.join(root, rel);
    if (fs.statSync(file).isFile()) files[rel.replaceAll("\\", "/")] = fs.readFileSync(file, "latin1");
  }
  return files;
}

/** A temp workspace repo with the docs pack, one package and a `@workerstack/repo` dependency. */
export function fixture(
  config = 'export default { packs: ["agents", "docs"], agents: { hosts: ["claude"] } }\n',
): string {
  const root = tempDir();
  write(root, CONFIG_FILE, config);
  const manifest = { name: "fixture", workspaces: ["packages/*"], devDependencies: { "@workerstack/repo": "^1.0.0" } };
  write(root, "package.json", JSON.stringify(manifest));
  write(root, "packages/api/package.json", JSON.stringify({ name: "@acme/api" }));
  write(root, "packages/api/references/INDEX.md", "# API worker\n");
  return root;
}

/** No post-passes, so a test with its own generators sees only their outputs. */
export const noPost: readonly PostPass[] = [];

/** Runs `repo sync` in `cwd` with `deps` over no post-passes unless they name some, capturing what it prints. */
export async function syncWith(cwd: string, deps: SyncDeps, ...args: string[]): Promise<Synced> {
  const out: string[] = [];
  const err: string[] = [];
  const io = { cwd, stdout: (s: string) => out.push(s), stderr: (s: string) => err.push(s) };
  const code = await runSync(args, io, { post: noPost, ...deps });
  return { code, stdout: out.join(""), stderr: err.join("") };
}

/** Runs `repo sync` in `cwd` with the bunfig and index generators and the git files pass. */
export function sync(cwd: string, ...args: string[]): Promise<Synced> {
  return syncWith(cwd, { generators: [bunfig, index], post: [gitFiles] }, ...args);
}

export function mtimes(root: string): number[] {
  return OUTPUTS.map((rel) => fs.statSync(path.join(root, rel)).mtimeMs);
}

/** Sets every output's times to 2020, so a rewrite shows in its mtime. */
export function age(root: string): void {
  const old = new Date("2020-01-01T00:00:00Z");
  for (const rel of OUTPUTS) fs.utimesSync(path.join(root, rel), old, old);
}

/** A whole, untracked file output at `rel`. */
export const file = (rel: string, content = `${rel}\n`): Output => ({
  kind: "file",
  path: rel,
  content,
  tracked: false,
  managed: "whole",
});

/** A whole, untracked link output at `rel`. */
export const link = (rel: string, target: string): Output => ({
  kind: "link",
  path: rel,
  target,
  tracked: false,
  managed: "whole",
});

/** A generator that returns exactly `outputs`, replacing the real ones. */
export const generating = (...outputs: Output[]): Generator[] => [() => ({ outputs, errors: [] })];

/** The same, with every path accepted as text, so these tests need not name registered formats. */
export const only = (...outputs: Output[]): { generators: Generator[]; formats: FormatEntry[] } => ({
  generators: generating(...outputs),
  formats: [{ match: () => true, format: "text", comment: null }],
});

/** The paths the manifest at `root` records. */
export function manifestPaths(root: string): string[] {
  const manifest: unknown = JSON.parse(read(root, MANIFEST_REL));
  if (typeof manifest !== "object" || manifest === null || !("paths" in manifest) || !Array.isArray(manifest.paths))
    throw new Error(`${MANIFEST_REL} has no paths`);
  return manifest.paths.filter((entry): entry is string => typeof entry === "string");
}

/** Whether anything, a dangling link too, stands at `rel`. */
export function exists(root: string, rel: string): boolean {
  try {
    fs.lstatSync(path.join(root, rel));
    return true;
  } catch {
    return false;
  }
}

/** Region `name` holding `body` as sync writes it, `#` or markdown by `open`. */
export const region = (open: string, close: string, [name, body]: [string, string]): string =>
  `${open}repo:${name} ${regionHash(body)}${close}\n${body}\n${open}/repo:${name}${close}\n`;

/** `expect.stringContaining(text)`, typed so an object literal can hold it. */
export function containing(text: string): unknown {
  return expect.stringContaining(text);
}
