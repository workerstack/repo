import { BASE_CONFIG } from "./base-config.ts";
import type { Pack } from "../config.ts";
import type { SyncContext } from "../sync/outputs.ts";
import type { PackageJson } from "../sync/workspace.ts";

export const HEADER = "# @generated by @workerstack/repo";

export function context(packs: Pack[], manifest: PackageJson = {}, files: Record<string, string> = {}): SyncContext {
  return {
    root: "/repo",
    config: { packs, agents: { hosts: [], skills: [] }, ...BASE_CONFIG },
    workspace: { root: "/repo", manifest, packages: [] },
    read: (rel) => files[rel] ?? null,
  };
}
