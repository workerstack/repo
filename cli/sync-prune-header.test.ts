import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

import { afterEach, describe, expect, it, vi } from "vitest";

import { CONFIG_FILE } from "./config.constants.ts";
import { childEnv } from "./env.ts";
import { toolEnv } from "./scripts/tool-env.ts";
import { runSync, type SyncDeps } from "./sync.ts";
import { put, tempDir as tempDirNamed, useTempDirs } from "./sync/__fixtures__/temp-dirs.ts";
import { headerStale } from "./sync/header-stale.ts";
import type { Output } from "./sync/outputs.ts";
import type { GitRun } from "./sync/standards.ts";

const OWNED = "# @generated by @workerstack/repo\n";
const LEGACY = "<!-- Generated by repo sync. Do not edit. -->\n";
const NEW_STALE = ".github/ISSUE_TEMPLATE/old.yml";
const LEGACY_STALE = "docs/old.md";
const KEPT: Record<string, string> = {
  "notes/line3.yml": `a: 1\nb: 2\n${OWNED}`,
  "notes/mine.md": "mine\n",
  "x/__fixtures__/ci.yml": OWNED,
};
function stale(rel: string) {
  return `repo sync: ${rel} is stale and would be removed; run \`bun repo sync\`\n`;
}

useTempDirs();
afterEach(() => {
  vi.unstubAllEnvs();
});

function tempDir(): string {
  return fs.realpathSync(tempDirNamed("workerstack-prune-"));
}

function write(root: string, files: Record<string, string>): void {
  for (const [rel, text] of Object.entries(files)) put(root, rel, text);
}

/** Git at `cwd` with none of the `GIT_*` variables a test stubs, so it acts on `cwd`'s own repo. */
function git(cwd: string, ...args: string[]): string {
  const result = spawnSync("git", args, { cwd, encoding: "utf8", env: toolEnv(childEnv()) });
  expect(result.status, result.stderr).toBe(0);
  return result.stdout;
}

function exists(root: string, rel: string) {
  return fs.existsSync(path.join(root, rel));
}

/** A consumer root with no manifest, as a fresh clone has; tracked and untracked files as given. */
function clone(tracked: Record<string, string>, untracked: Record<string, string> = {}, { inGit = true } = {}): string {
  const root = tempDir();
  write(root, {
    [CONFIG_FILE]: 'export default { packs: ["docs"] }\n',
    "package.json": JSON.stringify({ devDependencies: { "@workerstack/repo": "^1.0.0" }, name: "app" }),
    ...tracked,
  });
  if (inGit) {
    git(root, "init", "-q");
    git(root, "add", "--", ...Object.keys(tracked));
  }
  write(root, untracked);
  return root;
}

const keep: Output = { content: OWNED, kind: "file", managed: "whole", path: "keep.yml", tracked: true };
const DEPS: SyncDeps = {
  formats: [{ comment: null, format: "text", match: () => true }],
  generators: [() => ({ errors: [], outputs: [keep] })],
  post: [],
};

async function sync(cwd: string, ...args: string[]) {
  const out: string[] = [];
  const err: string[] = [];
  const code = await runSync(args, { cwd, stderr: (s) => err.push(s), stdout: (s) => out.push(s) }, DEPS);
  return { code, stderr: err.join(""), stdout: out.join("") };
}

const TRACKED = { [LEGACY_STALE]: LEGACY, [NEW_STALE]: OWNED, "keep.yml": OWNED, ...KEPT };

describe("runSync prune by header, with no manifest", () => {
  it("names each tracked file with our header that no output names under --check and exits 1", async () => {
    const root = clone(TRACKED, { "loose/untracked.yml": OWNED });
    expect(await sync(root, "--check")).toStrictEqual({
      code: 1,
      stderr: stale(NEW_STALE) + stale(LEGACY_STALE),
      stdout: "",
    });
    expect(exists(root, NEW_STALE)).toBe(true);
  });

  it("removes them and keeps an untracked copy, one under fixtures, one on line 3 and a user file", async () => {
    const root = clone(TRACKED, { "loose/untracked.yml": OWNED });
    expect(await sync(root)).toMatchObject({ code: 0, stderr: "" });
    expect(exists(root, NEW_STALE)).toBe(false);
    expect(exists(root, LEGACY_STALE)).toBe(false);
    for (const rel of [...Object.keys(KEPT), "keep.yml", "loose/untracked.yml"]) expect(exists(root, rel)).toBe(true);
    expect(await sync(root, "--check")).toStrictEqual({ code: 0, stderr: "", stdout: "repo sync: up to date\n" });
  });
});

describe("runSync prune by header, where git has no repo of its own", () => {
  it("prunes nothing by header outside a git repo", async () => {
    const root = clone({}, { [LEGACY_STALE]: LEGACY, [NEW_STALE]: OWNED }, { inGit: false });
    expect(await sync(root, "--check")).toMatchObject({
      code: 1,
      stderr: "repo sync: keep.yml is out of date; run `bun repo sync`\n",
    });
    expect(await sync(root)).toMatchObject({ code: 0, stderr: "" });
    expect(exists(root, NEW_STALE) && exists(root, LEGACY_STALE)).toBe(true);
  });

  it("reads its own repo when GIT_DIR and GIT_INDEX_FILE name another, and leaves that one alone", async () => {
    const root = clone({ [NEW_STALE]: OWNED }, { "loose/untracked.yml": OWNED });
    const other = clone({ "loose/untracked.yml": OWNED });
    const before = fs.readFileSync(path.join(other, ".git/index"));
    vi.stubEnv("GIT_DIR", path.join(other, ".git"));
    vi.stubEnv("GIT_INDEX_FILE", path.join(other, ".git/index"));
    const result = await sync(root);
    vi.unstubAllEnvs();
    expect(result).toMatchObject({ code: 0, stderr: "" });
    expect(exists(root, NEW_STALE)).toBe(false);
    expect(exists(root, "loose/untracked.yml")).toBe(true);
    expect(fs.readFileSync(path.join(other, ".git/index"))).toStrictEqual(before);
    expect(git(other, "ls-files")).toBe("loose/untracked.yml\n");
    expect(exists(other, "loose/untracked.yml")).toBe(true);
  });
});

/** A git that answers every command with `status` and `stdout`. */
function answer(status: number | null, stdout = ""): GitRun {
  return () => ({ status, stderr: "", stdout });
}
/** A git that answers status 1 with nothing and records the args of each command in `calls`. */
function recording(calls: (readonly string[])[]): GitRun {
  return (_root, given) => {
    calls.push(given);
    return { status: 1, stderr: "", stdout: "" };
  };
}

describe("headerStale", () => {
  it("asks git for the tracked text files holding any header line, literally", () => {
    const calls: (readonly string[])[] = [];
    expect(headerStale("/r", [], recording(calls))).toStrictEqual([]);
    const args = calls[0] ?? [];
    expect(args.slice(0, 5)).toStrictEqual(["grep", "-l", "-z", "-I", "-F"]);
    expect(args).toContain("@generated by @workerstack/repo");
    expect(args).toContain(LEGACY.trimEnd());
    expect(args.filter((arg) => arg === "-e")).toHaveLength((args.length - 5) / 2);
  });

  it("gives none when git fails or cannot start", () => {
    expect(headerStale("/r", [], answer(128, "a.yml\0"))).toStrictEqual([]);
    expect(headerStale("/r", [], answer(null))).toStrictEqual([]);
  });

  it("keeps only readable files outside fixtures and the outputs, in one spelling, whose header is ours", () => {
    const root = tempDir();
    write(root, { "a.yml": OWNED, "b.yml": OWNED, "c.yml": `x\n${OWNED}`, "x/__fixtures__/d.yml": OWNED });
    const listed = ["a.yml", "./b.yml", "c.yml", "x\\__fixtures__\\d.yml", "missing.yml", "../up.yml", ""].join("\0");
    expect(headerStale(root, [{ ...keep, path: "b.yml" }], answer(0, listed))).toStrictEqual(["a.yml"]);
  });
});
