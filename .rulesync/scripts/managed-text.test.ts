import { describe, expect, it } from "vitest";
import { mergeBlock, mergeSection } from "./managed-text.ts";

describe("mergeBlock", () => {
  it("writes LF with one trailing newline whatever the input endings", () => {
    expect(mergeBlock("a\r\n# >>> m\r\nold\r\n# <<< m\r\nb\r\n\r\n", "# >>> m", "# <<< m", "new")).toEqual({
      ok: true,
      text: "a\n# >>> m (generated by repo sync)\nnew\n# <<< m\nb\n",
    });
  });
});

describe("mergeSection", () => {
  it("replaces only the first section of a name and ignores a stray closer before it", () => {
    const text = "<!-- /repo:x -->\n<!-- repo:x -->\nold\n<!-- /repo:x -->\n<!-- repo:x -->\n<!-- /repo:x -->\n";
    expect(mergeSection(text, "x", "new")).toEqual({
      ok: true,
      text: "<!-- /repo:x -->\n<!-- repo:x -->\nnew\n<!-- /repo:x -->\n<!-- repo:x -->\n<!-- /repo:x -->\n",
    });
  });

  it("returns the unclosed opener as an error without a file name", () => {
    expect(mergeSection("<!-- repo:x -->\n", "x", "")).toEqual({
      ok: false,
      error: '"<!-- repo:x -->" has no closing "<!-- /repo:x -->"',
    });
  });
});
